"""Stage B for noncyclic G: twisted b = 1 slices on G = product of components with coprime orders
(theory/abgroup.py: ('C', q) cyclic prime power, ('E', p, k) elementary abelian with GL(k, p)).

Every cyclic subgroup <u> of Aut(G) = prod Aut(component), u = (sigma per component) up to conjugacy of the GL parts
(slices depend only on the subgroup, up to relabelling C <-> D); twists 'BC' (d even), 'BCD' (3 | d), and 'id' with
--id; orbits in [RMIN, RMAX].  Exact quotient screens over every u-stable subgroup H = prod of u-stable component
subgroups (all-lags test when small, else lag-0 energy), then the Gaussian for survivors.  Restart-safe JSONL.
usage: b1tw_ab_screen.py OUT v SPEC [--rmin R] [--rmax R] [--id]
SPEC: components separated by '+', e.g. E2.2+C167 (Z_2^2 x Z_167), C2+E3.2+C41, E2.3+C67"""
import sys, os, json, time, math, itertools
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "theory"))
from abgroup import AbGroup, AutGroup, gl_elements
from b1tw_ab import AbSlice, gaussian, quotient_screen


def parse(spec):
    comps = []
    for c in spec.split("+"):
        if c[0] == "E":
            p, k = map(int, c[1:].split(".")); comps.append(("E", p, k))
        else:
            comps.append(("C", int(c[1:])))
    return comps


def subspaces(p, k):
    """all subspaces of GF(p)^k as frozensets of vectors (tuples)"""
    vecs = [v for v in itertools.product(range(p), repeat=k) if any(v)]
    out = {frozenset([tuple([0] * k)])}
    frontier = list(out)
    while frontier:
        nf = []
        for S in frontier:
            for v in vecs:
                if v in S: continue
                T = set(S)
                for s in S:
                    for a in range(1, p):
                        T.add(tuple((x + a * y) % p for x, y in zip(s, v)))
                T = frozenset(T)
                if T not in out: out.add(T); nf.append(T)
        frontier = nf
    return out


def component_subgroups(c, a):
    """u-stable subgroups of one component under its automorphism a, as lists of generator coordinate vectors"""
    if c[0] == "C":
        q = c[1]; p = min(f for f in range(2, q + 1) if q % f == 0)
        out = []; e = q
        while True:
            out.append([[q // e]] if e > 1 else [])       # subgroup of order e generated by q/e
            if e == 1: break
            e //= p
        return out
    p, k = c[1], c[2]; M = np.array(a) % p; out = []
    for S in subspaces(p, k):
        if all(tuple(((M @ np.array(s)) % p).tolist()) in S for s in S):
            out.append([list(s) for s in S if any(s)])
    return out


def main():
    a = sys.argv[1:]
    OUT, v, spec = a[0], int(a[1]), a[2]
    opt = lambda f, d: int(a[a.index(f) + 1]) if f in a else d
    rmin, rmax = opt("--rmin", 6), opt("--rmax", 150)
    tws = ("id", "BC", "BCD") if "--id" in a else ("BC", "BCD")
    comps = parse(spec); G = AbGroup(comps); assert G.n == v - 1, (G.n, v)
    AG = AutGroup(G)
    done = set()
    if os.path.exists(OUT):
        for l in open(OUT): z = json.loads(l); done.add((z["spec"], z["key"], z["tw"]))
    out = open(OUT, "a")
    # conjugacy-class representatives for GL parts (by brute conjugation), all units for cyclic parts
    reps_per = []
    for i, c in enumerate(comps):
        els, mult, ident = AG.parts[i]
        if c[0] == "E":
            nE = len(els); inv = [int(np.flatnonzero(mult[j] == ident)[0]) for j in range(nE)]
            seen, reps = set(), []
            for j in range(nE):
                if j in seen: continue
                seen |= {int(mult[mult[P, j], inv[P]]) for P in range(nE)}; reps.append(j)
            reps_per.append(reps)
        else:
            reps_per.append(list(range(len(els))))
    seen_sub = set()
    for x in itertools.product(*reps_per):
        d = AG.elem_order(x)
        if d == 1: continue
        # subgroup key: the set of its elements
        S = AG.closure([x]); key = min(S)
        if (S in seen_sub): continue
        seen_sub.add(S)
        aut = AG.to_aut(x); up = G.aut_perm(aut)
        for tw in tws:
            if (tw == "BC" and d % 2) or (tw == "BCD" and d % 3): continue
            k = "-".join(map(str, x))
            if (spec, k, tw) in done: continue
            sl = AbSlice(G, up, tw, label=k)
            if not (rmin <= sl.r <= rmax): continue
            t0 = time.time()
            rec = dict(v=v, spec=spec, key=k, aut=[np.asarray(t).tolist() if not isinstance(t, (int, np.integer)) else int(t) for t in aut],
                       d=d, tw=tw, orbits=sl.r, classes=sl.L, minus1_in_U=bool(sl.minus1_in_U),
                       group_bits={g: len(b) for g, b in sl.groups.items()})
            # u-stable subgroups H (products of component subgroups), excluding 0 and G
            per = [component_subgroups(c, t) for c, t in zip(comps, aut)]
            col = 0; embeds = []
            for c in comps:
                w = c[2] if c[0] == "E" else 1; embeds.append((col, w)); col += w
            killed = None; tested = 0
            Hs = []
            for choice in itertools.product(*per):
                gens = []
                for (c0, w), gl in zip(embeds, choice):
                    for gvec in gl:
                        z = [0] * G.k; z[c0:c0 + w] = gvec; gens.append(int(G.idx(z)))
                order = 1
                for c, gl in zip(comps, choice):
                    if c[0] == "C": order *= (c[1] // gl[0][0]) if gl else 1
                    else: order *= len(gl) + 1
                if 1 < order < G.n: Hs.append((order, gens))
            for order, gens in sorted(Hs, key=lambda t: -t[0]):           # small quotients first
                ok, how = quotient_screen(sl, gens); tested += 1
                if not ok:
                    killed = dict(H_order=order, quotient=G.n // order, test=how); break
            rec.update(alive=killed is None, killed=killed, subgroups_tested=tested)
            if killed is None:
                ga = gaussian(sl, N=20000)
                rec.update({kk: ga.get(kk) for kk in ("log2_rowsum_configs", "feasible", "why", "n_cond", "log2E", "steps", "mahal")})
            rec["secs"] = round(time.time() - t0, 1)
            out.write(json.dumps(rec) + "\n"); out.flush(); print(json.dumps(rec), flush=True)


if __name__ == "__main__":
    main()
