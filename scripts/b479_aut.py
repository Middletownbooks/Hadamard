"""v=479 (b=3, G=Z2^2 x Z119): stabiliser of the core under Aut(G)=GL(2,2) x (Z/119)*, up to per-block translation."""
import sys,itertools,numpy as np; sys.path.insert(0,'scripts')
from hadlib import all_cores, translate_match
from math import gcd
c=[x for x in all_cores() if x.v==479][0]; co=c.coords()
GL=[np.array(M).reshape(2,2) for M in itertools.product([0,1],repeat=4) if (M[0]*M[3]-M[1]*M[2])%2]
units=[u for u in range(1,119) if gcd(u,119)==1]
stab={k:[] for k in range(4)}
for gi,S in enumerate(GL):
    for u in units:
        img=np.stack([(co[:,:2]@S.T)%2, (co[:,2:3]*u)%119],axis=1).reshape(len(co),3) if False else np.concatenate([(co[:,:2]@S.T)%2,(co[:,2:3]*u)%119],axis=1)
        perm=c.idx(img)
        for k in range(4):
            if translate_match(c.X[k],c.X[k][perm],c): stab[k].append((gi,u))
common=set(stab[0])&set(stab[1])&set(stab[2])&set(stab[3])
print('per-block stabiliser sizes',[len(stab[k]) for k in range(4)],' common',len(common))
print('common elements (GL index, mu):',sorted(common)[:20])
# orbit count r under the common group (acting on G, ignoring translations)
if common:
    H=list(common); seen=np.zeros(c.m,bool); r=0
    for i in range(c.m):
        if seen[i]: continue
        r+=1
        for gi,u in H:
            S=GL[gi]; x=co[i]; y=np.concatenate([(S@x[:2])%2,[(x[2]*u)%119]]); seen[c.idx(y)]=True
    print('orbits r (if blocks invariant about 0; translations ignored) =',r)
# affine orbit counts per block: maps x -> A x + t with t found by translate_match (group generated by all 12)
for k in range(4):
    parent=list(range(c.m))
    def f(a):
        while parent[a]!=a: parent[a]=parent[parent[a]]; a=parent[a]
        return a
    for gi,u in H:
        S=GL[gi]; img=np.concatenate([(co[:,:2]@S.T)%2,(co[:,2:3]*u)%119],axis=1); perm=c.idx(img)
        ts=translate_match(c.X[k],c.X[k][perm],c)
        t=co[ts[0]]
        # translate_match: x(i+t) = x(A i)  -> join (A i) with (i + t)
        sh=c.idx(np.concatenate([(co[:,:2]+t[:2])%2,(co[:,2:3]+t[2])%119],axis=1))
        for i in range(c.m):
            a,b=f(int(perm[i])),f(int(sh[i]))
            if a!=b: parent[a]=b
    orb=len({f(i) for i in range(c.m)})
    # sanity: block constant on orbits
    ok=all(len({c.X[k][i] for i in range(c.m) if f(i)==rt})==1 for rt in {f(i) for i in range(c.m)})
    print('block',k,'affine orbits',orb,'constant on orbits',ok)
