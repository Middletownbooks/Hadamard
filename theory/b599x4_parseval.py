def orbits(mods, gens):
    """S-orbits on G = prod Z_mods for S generated by per-axis scalars gens"""
    pts = list(itertools.product(*[range(n) for n in mods]))
    idx = {p: i for i, p in enumerate(pts)}
    lab = -np.ones(len(pts), np.int64); orbs = []
    for p in pts:
        if lab[idx[p]] >= 0: continue
        O = {p}; fr = [p]
        while fr:
            g = fr.pop()
            for u in gens:
                h = tuple((a * c) % n for a, c, n in zip(g, u, mods))
                if h not in O: O.add(h); fr.append(h)
        for g in O: lab[idx[g]] = len(orbs)
        orbs.append(sorted(O))
    return pts, idx, lab, orbs


