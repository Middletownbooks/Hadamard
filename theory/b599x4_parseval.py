def count_cores(mods, gens, T):
    """exhaustive number of ordered core quadruples of the slice (2+2 join on exact PAF vectors)"""
    pts, idx, lab, orbs = orbits(mods, gens)
    r = len(orbs)
    X = np.array([[1 - 2 * ((s >> o) & 1) for o in range(r)] for s in range(2 ** r)])[:, lab]
    ax = tuple(range(1, 1 + len(mods)))
    F = np.fft.fftn(X.reshape((-1,) + tuple(mods)), axes=ax)
    P = np.rint(np.fft.ifftn(np.abs(F) ** 2, axes=ax).real).astype(np.int64).reshape(len(X), -1)
    keys = defaultdict(int)
    for i in range(len(P)):
        for j in range(len(P)): keys[(P[i] + P[j]).tobytes()] += 1
    tot = 0
    for i in range(len(P)):
        for j in range(len(P)): tot += keys.get((T - P[i] - P[j]).astype(np.int64).tobytes(), 0)
    return r, tot


