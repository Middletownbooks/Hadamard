r"""Generalised census of bordered-GS structures with a character set T [M orbit counts, coset-Parseval, Q-level
gate; E Q-level stratified count read at the true target].

Families (t = |T|, q = |Q|, n = |G| + t):
  k4     Q of order 4 (Z_2^2 or Z_4), T = the 3 nontrivial characters                 (n = 3 mod 4)
  k4one  Q of order 4, T = {1} + two nontrivial characters (Z_4: {1, chi, chi^3}; Z_2^2: {1, chi_a, chi_b})
  k6     Q = Z_6, T = the 5 nontrivial characters ([EKLO] Theorem 7, k = 6)
  k8     Q of order 8, T = the 7 nontrivial characters ([EKLO] Theorem 7, k = 8)
  z3all  Q = Z_3, T = all 3 characters (Kumar, NOTES section 18; 2148)
  prod12 Q = Z_2^2 x Z_3, T = (nontrivial on Z_2^2) x (all on Z_3), t = 9 (Kumar section 18)
G = P x O (P the 2-part, O the odd part), K = K_P x K_O with G/K = Q; S <= Aut(P)_{K_P} x Aut(O)_{K_O} preserving
Gamma o pi, generated by one or two elements, up to conjugation by Aut(P)_{K_P}.  Gamma(g + K) = 4 sum_{chi in T} chi(g)
is computed from the characters of G that are trivial on K.
usage: python3 theory/bt_census2.py OUT.jsonl --fam k4one --ns 839,863 [--rmin 8] [--rmax 140] [--part i/W]
"""
import sys, os, json, math, time, argparse, itertools, hashlib
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bt_engine as E, bt_chain as C, bt_gates as BG, bt_census as BC, bt_census_run as R

FAMS = {
    'k4': dict(t=3, q2=4, q3=1), 'k4one': dict(t=3, q2=4, q3=1), 'k6': dict(t=5, q2=2, q3=3),
    'k8': dict(t=7, q2=8, q3=1), 'z3all': dict(t=3, q2=1, q3=3), 'prod12': dict(t=9, q2=4, q3=3),
}


def chars_trivial_on(G, Kel):
    """characters xi of G trivial on K (as index arrays into G, via <xi, g> = sum xi_j g_j / m_j)"""
    m = G.marr.astype(float)
    ph = (G.co[:, None, :] * G.co[Kel][None, :, :] / m).sum(-1)
    ok = np.all(np.abs(ph - np.round(ph)) < 1e-9, axis=1)
    return np.flatnonzero(ok)


def char_order(G, xi):
    return G.order(int(xi))


def gamma_options(fam, G, Kel, coset, q):
    """list of (label, Gamma per coset) for the family's T choices"""
    xis = chars_trivial_on(G, Kel)
    m = G.marr.astype(float)
    reps = np.array([np.flatnonzero(coset == c)[0] for c in range(q)])
    val = lambda T: np.rint(4 * sum(np.cos(2 * np.pi * (G.co[x] * G.co[reps] / m).sum(-1)) for x in T)).astype(np.int64) \
        if len(T) else np.zeros(q, np.int64)
    nontriv = [x for x in xis if x != 0]
    out = []
    if fam in ('k4', 'k6', 'k8'):
        out.append(('nontrivial', val(nontriv)))
    elif fam == 'z3all':
        out.append(('all', val(list(xis))))
    elif fam == 'k4one':
        o4 = [x for x in nontriv if char_order(G, x) == 4]
        if o4:                                                    # Q = Z_4: {1, chi, chi^3}
            out.append(('Z4:1+order4', val([0] + o4)))
        else:                                                     # Q = Z_2^2: {1, chi_a, chi_b} (all choices)
            for drop in nontriv:
                out.append((f'Z2^2:1+all-but-{int(drop)}', val([0] + [x for x in nontriv if x != drop])))
    elif fam == 'prod12':
        # T = (nontrivial on the Z_2^2 part) x (all on Z_3): chi with chi^3 nontrivial (i.e. 2-part nontrivial)
        T = [x for x in xis if char_order(G, x) % 2 == 0]
        out.append(('prod12', val(T)))
    return out


def two_options_q(a, q2, cap=2 ** 20):
    """2-groups P of order 2^a (enumerable automorphisms) with subgroups K_P of index q2, up to Aut(P)"""
    out = []
    for part in BC.partitions(a):
        P = BC.TwoGroup(part)
        if P.n_endos() > cap:
            continue
        mats, perms = P.automorphisms(cap)
        if q2 == 1:
            Ks = [np.arange(P.G.n)]
        else:
            Ks = P.subgroups_of_index(q2)
        seen = set(); reps = []
        for KP in Ks:
            k = KP.tobytes()
            if k in seen:
                continue
            reps.append(KP)
            for p in perms:
                seen.add(np.sort(p[KP]).tobytes())
        for KP in reps:
            keep = [i for i, p in enumerate(perms) if set(p[KP].tolist()) == set(KP.tolist())]
            out.append(dict(P=P, KP=KP, mats=[mats[i] for i in keep], perms=[perms[i] for i in keep]))
    return out


def odd_options_q(o, q3, maxgl=5):
    """odd parts O of order o with K_O of index q3 (q3 in {1, 3}); returns (mods, gl_pairs, K_O generators).
    Z_p^2 with GL(2, p) is included only for p <= maxgl (971's Z_11^2 is handled by theory/bt_census971.py)."""
    out = []
    for mods, gl in R.odd_options(o):
        if gl and mods[gl[0][0]] > maxgl:
            continue
        if q3 == 1:
            out.append((mods, gl, [tuple(int(i == j) for i in range(len(mods))) for j in range(len(mods))]))
            continue
        # K_O = index-3 subgroup: choose a factor divisible by 3 and take 3x that factor (or drop a Z_3)
        for j, mj in enumerate(mods):
            if mj % 3:
                continue
            gens = []
            for i in range(len(mods)):
                v = [0] * len(mods); v[i] = 3 if i == j else 1; gens.append(tuple(v))
            out.append((mods, gl, gens))
            if mods.count(mj) > 1 and gl:                         # equal factors (Z_3^2): one choice suffices
                break
    return out


def structures(n, fam, rmin, rmax):
    F = FAMS[fam]
    t, q2, q3 = F['t'], F['q2'], F['q3']
    m = n - t
    if m <= 0 or m % (q2 * q3):
        return
    a = 0; o = m
    while o % 2 == 0:
        o //= 2; a += 1
    if o % q3:
        return
    for popt in two_options_q(a, q2):
        P = popt['P']
        for omods, gl, KOgens in odd_options_q(o, q3):
            O = BC.OddPart(omods, gl)
            omats = O.automorphisms() if omods else [np.zeros((0, 0), np.int64)]
            mods = P.mods + omods
            G = E.Grp(mods)
            # K
            Kgens = []
            for g in popt['KP']:
                if g:
                    Kgens.append(tuple(int(c) for c in P.G.co[g]) + (0,) * len(omods))
            for v in KOgens:
                Kgens.append((0,) * len(P.mods) + tuple(v))
            Kel = G.subgroup(Kgens) if Kgens else np.array([0])
            # cosets
            Kmask = np.zeros(G.n, bool); Kmask[Kel] = True
            cos = -np.ones(G.n, np.int64); qn = 0
            for g in range(G.n):
                if cos[g] < 0:
                    cos[G.idx(G.co[g] + G.co[Kel])] = qn; qn += 1
            if qn != q2 * q3:
                continue
            # group elements as permutations of G (a, b) -> block matrix
            pm = popt['mats']; om = omats
            for label, gam in gamma_options(fam, G, Kel, cos, qn):
                F_tgt = -gam[cos]
                Pp = [G.perm_of(E.block_diag(M, np.eye(len(omods), dtype=np.int64)) if omods else M) for M in pm]
                Op = [G.perm_of(E.block_diag(np.eye(len(P.mods), dtype=np.int64), M)) for M in om] if omods else \
                    [np.arange(G.n)]
                okP = [i for i, p in enumerate(Pp) if Kmask[p][Kmask].all() and (F_tgt[p] == F_tgt).all()]
                okO = [j for j, p in enumerate(Op) if Kmask[p][Kmask].all() and (F_tgt[p] == F_tgt).all()]
                TP = BC.AutTable([popt['perms'][i] for i in okP])
                TO = BC.AutTable([O.G.perm_of(om[j]) for j in okO]) if omods else BC.AutTable([np.zeros(1, np.int64)])
                res = BC.enumerate_S(TP, TO, rmin, rmax)
                seen = set()
                for S, gens in res:
                    key = BC.conj_canonical(TP, TO, S)
                    if key in seen:
                        continue
                    seen.add(key)
                    mats = []
                    for ga, gb in gens:
                        Ma = pm[okP[ga]]; Mb = om[okO[gb]] if omods else np.zeros((0, 0), np.int64)
                        mats.append((E.block_diag(Ma, Mb) if omods else Ma).tolist())
                    yield dict(n=n, fam=fam, T=label, Pmods=list(P.mods), Omods=list(omods),
                               Kgens=[list(k) for k in Kgens], gamma=gam.tolist(), gens=mats,
                               order=len(S), r=BC.orbit_count(TP, TO, S))


def build(rec):
    gam = {c: v for c, v in enumerate(rec['gamma'])}
    return E.BStruct(tuple(rec['Pmods'] + rec['Omods']), [tuple(k) for k in rec['Kgens']], gam,
                     [np.array(M) for M in rec['gens']], name=f"{rec['n']}:{rec['fam']}:{rec['T']}")


def key_of(rec):
    return hashlib.sha1(json.dumps([rec['n'], rec['fam'], rec['T'], rec['Pmods'], rec['Omods'], rec['Kgens'],
                                    rec['gens']]).encode()).hexdigest()[:16]


def alpha_trivial_on_K(st):
    """does S contain an element fixing K pointwise and acting with order 3 on Q (dead for Q = Z_2^2) [P]"""
    if st.q != 4:
        return False
    els = E.group_elements(st.bperms[0], st.G.n, cap=5000)
    Kel = st.Kel
    for p in els:
        if not (p[Kel] == Kel).all():
            continue
        # action on cosets
        act = np.array([st.coset[p[st.coset_rep[c]]] for c in range(st.q)])
        a2 = act[act]
        if not (act == np.arange(st.q)).all() and (act[a2] == np.arange(st.q)).all():
            return True
    return False


def evaluate(rec, N=1200, maxq=3, maxtot=24, seed=1, prefilter=-45.0):
    t0 = time.time()
    st = build(rec)
    out = dict(rec); out['key'] = key_of(rec)
    out['r'] = st.r[0]; out['e'] = st.e
    out['orbit_sizes'] = np.bincount(st.sizes[0]).nonzero()[0].tolist()
    rule = 4 * st.r[0] - 6.5 * st.e
    out['rule'] = rule
    if prefilter is not None and rule < prefilter:
        out['verdict'] = f'skipped (4r - 6.5e = {rule:.1f} < {prefilter})'
        out['secs'] = round(time.time() - t0, 1); return out
    if alpha_trivial_on_K(st):
        out['verdict'] = 'no core [P] (order-3 element of S trivial on K)'
        out['secs'] = round(time.time() - t0, 1); return out
    cp = st.coset_parseval()
    out['cp'] = [(d['p'], round(d['margin'], 3)) for d in cp]
    out['inv_subgroups'] = [len(Nn) for Nn in st.invariant_subgroups()]
    if any(d['dead'] for d in cp):
        out['verdict'] = 'no core [P] (coset-Parseval)'
        out['secs'] = round(time.time() - t0, 1); return out
    g = BG.Gates(st)
    pats = BG.row_patterns(st) if st.gamma[0] != 4 * st.q or True else None
    # row patterns: sum r^2 = (4n if trivial char not in T else 4t)
    n4 = 4 * st.nH
    triv_in_T = abs(sum(st.gamma) / st.q / 4 - 1) < 1e-9          # (1/q) sum Gamma = 4 [1 in T]
    tot_sq = 4 * st.t if triv_in_T else n4
    par = st.G.n % 2
    lim = math.isqrt(tot_sq); pats = []
    for a in range(par, lim + 1, 2):
        for b in range(a, lim + 1, 2):
            for c in range(b, lim + 1, 2):
                d2 = tot_sq - a * a - b * b - c * c
                if d2 < c * c: continue
                d = math.isqrt(d2)
                if d * d == d2 and d % 2 == par: pats.append((a, b, c, d))
    try:
        qs = g.q_level(patterns=pats)
    except MemoryError as e:
        out['verdict'] = f'Q-level cap ({e})'; out['secs'] = round(time.time() - t0, 1); return out
    out['q_patterns'] = [list(map(int, q[0])) for q in qs]
    out['q_solutions'] = int(sum(len(q[1]) for q in qs))
    if not qs:
        out['verdict'] = 'no core [M] (Q-level empty)'; out['secs'] = round(time.time() - t0, 1); return out
    import q523_gauss as QG
    rng = np.random.default_rng(seed)
    V = np.zeros((N, st.ncls), np.int64)
    for i in range(4):
        X = rng.choice(np.array([-1, 1], np.int8), size=(N, st.r[i]))
        V += C.class_paf_orbits(st, i, X)
    gw = QG.gauss_bits(V, st.cls_target)
    out['log2E_whole'] = round(sum(st.r) - gw['bits'], 2) if np.isfinite(gw['bits']) else None
    tot = 0.0; terms = []
    for rows, sol, L in qs:
        w = BG.pattern_weight(tuple(abs(x) for x in rows))
        nq = max(1, min(maxq, maxtot // max(1, len(qs))))
        idx = np.arange(len(sol)) if len(sol) <= nq else rng.choice(len(sol), nq, replace=False)
        vals = []
        for k in idx:
            s = sol[k]
            zs = [L[i][0][s[i]] for i in range(4)]
            lm = sum(math.log2(L[i][1][s[i]]) for i in range(4))
            r = BG.stratified_bits(st, g.qQ, zs, N=N, seed=seed + int(k))
            vals.append(lm - r['bits'] if np.isfinite(r['bits']) else -math.inf)
            terms.append(dict(rows=list(map(int, rows)), log2E=round(vals[-1], 2) if np.isfinite(vals[-1]) else None,
                              mahal=r.get('mahal')))
        vals = np.array(vals)
        tot += w * len(sol) * np.mean(np.where(np.isfinite(vals), 2.0 ** vals, 0.0))
    out['log2E_Q'] = round(math.log2(tot), 2) if tot > 0 else None
    out['q_terms'] = sorted(terms, key=lambda d: -(d['log2E'] if d['log2E'] is not None else -1e9))[:5]
    out['verdict'] = 'passes Q-level'
    out['secs'] = round(time.time() - t0, 1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out'); ap.add_argument('--fam', default='k4one')
    ap.add_argument('--ns', default='599,643,719,739,751,839,859,863,907,947,955,971')
    ap.add_argument('--rmin', type=int, default=8); ap.add_argument('--rmax', type=int, default=140)
    ap.add_argument('--N', type=int, default=1200); ap.add_argument('--part', default='0/1')
    ap.add_argument('--list-only', action='store_true')
    a = ap.parse_args()
    pi, pw = map(int, a.part.split('/'))
    done = set()
    if os.path.exists(a.out):
        for line in open(a.out):
            try: done.add(json.loads(line)['key'])
            except Exception: pass
    k = 0
    for n in map(int, a.ns.split(',')):
        t0 = time.time()
        try:
            recs = list(structures(n, a.fam, a.rmin, a.rmax))
        except MemoryError as e:
            print(f'n = {n}: enumeration cap ({e})', flush=True); continue
        print(f'n = {n} fam {a.fam}: {len(recs)} structures ({time.time() - t0:.1f}s)', flush=True)
        if a.list_only:
            continue
        for rec in recs:
            k += 1
            if (k - 1) % pw != pi or key_of(rec) in done:
                continue
            try:
                res = evaluate(rec, N=a.N)
            except Exception as e:
                res = dict(rec, key=key_of(rec), verdict=f'error: {type(e).__name__}: {e}')
            with open(a.out, 'a') as f:
                f.write(json.dumps(res) + '\n')
            print(json.dumps({x: res.get(x) for x in ('n', 'fam', 'T', 'Pmods', 'Omods', 'order', 'r', 'e', 'verdict',
                                                     'q_solutions', 'log2E_Q', 'log2E_whole', 'secs')}), flush=True)


if __name__ == '__main__':
    main()
