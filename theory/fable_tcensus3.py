#!/usr/bin/env python3
"""Census of small character-border slices with a general character set T over Q = Z_2^a, a = 4, 5, 6.  [M]
(Plan item 1, logs/fable_fresh/PLAN_phase3.md; extends theory/fable_tcensus2.py, whose Q-level solver is reused.)

Setting (report/fable_fresh_answer.md section 7): G = Q x S, |G| = 2^a s, n = 4p = 4(2^a s + t), t = |T|; four +-1
sequences on G with sum_k |xhat_k(chi)|^2 = 4t for chi in T (characters of Q, trivial on S) and = 4p otherwise;
a border of width 4t completes the core (Kumar's character-bordered family, his search/NOTES.md section 18).

Multiplier group H = Sigma x U: Sigma acts on Q by field multiplications on a decomposition Q = (+) F_{2^d_i}
(products of subgroups C_i of F_{2^d_i}^*, and cyclic diagonal subgroups of such products), U is a cyclic group of
units of Z_s (S cyclic).  Sequences are constant on H-orbits; r = (#Sigma-orbits on Q)(#U-orbits on S) per block.

Exact gates, in order (each a necessary condition; the record names the first that fails):
  axis   U = all units of a prime s >= 5: dead by the axis gate of report section 8a [P]
  G1     cell energy: sum over the 4 * 2^a cells of y^2 = (4 t^2 + 4 p (2^a - t)) / 2^a, reachable with the cell
         alphabet Y = {sum over U-orbits B of S of +-|B|} [P: Parseval on Q]
  G2     Q-level: theory/fable_tcensus2.qlevel (blocks constant on Sigma-orbits, values in Y, exact energy-vector
         join); here a copy that also returns the multisets of squared row sums of the solutions
  G3     S-level (dual compression): w_k(z) = sum_q x_k(q, z), constant on U-orbits, values in
         W = {sum over Sigma-orbits A of Q of +-|A|}; sum_k PAF(w_k)(h) = (T0 - 4p)/s for h != 0, where
         T0 = 4t if the trivial character is in T and 4p otherwise [P: Parseval on S]; exact 2 + 2 join on the PAF
         vector over the orbits of <U, -1> on the lags
  G4     the multisets of squared row sums allowed by G2 and by G3 must intersect
Output: logs/fable_fresh/tcensus3.jsonl (restart-safe: keys already present are skipped).
Usage:  fable_tcensus3.py [--a 4,5,6] [--rmax 64] [--qorbmax 12] [--primes 599,719] [--out FILE]
        fable_tcensus3.py --control      (reproduces the 599 records of logs/fable_fresh/tcensus2.jsonl)
"""
import sys, os, json, itertools, math, time, collections
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fable_tcensus import orbits as zorbits, cyc_subgroups
from fable_tclasses import kind

POLY = {2: 0b111, 3: 0b1011, 4: 0b10011, 5: 0b100101, 6: 0b1000011}

def gf_mul(x, y, d):
    r = 0
    while y:
        if y & 1: r ^= x
        y >>= 1; x <<= 1
        if x >> d: x ^= POLY[d]
    return r

def gf_gen(d):
    """a primitive element of F_{2^d} (d >= 2)"""
    n = (1 << d) - 1
    for g in range(2, 1 << d):
        x = 1; o = 0
        while True:
            x = gf_mul(x, g, d); o += 1
            if x == 1: break
        if o == n: return g
    raise ValueError(d)

def gf_pow(g, e, d):
    x = 1
    for _ in range(e): x = gf_mul(x, g, d)
    return x

def partitions(a):
    def rec(n, mx):
        if n == 0: yield []; return
        for k in range(min(n, mx), 0, -1):
            for rest in rec(n - k, k): yield [k] + rest
    yield from rec(a, a)

def dual_perm(img, K):
    dot = lambda m, q: bin(m & q).count('1') & 1
    out = [None] * K
    for m in range(K):
        for m2 in range(K):
            if all(dot(m2, img[q]) == dot(m, q) for q in range(K)): out[m] = m2; break
    assert None not in out
    return out

def group_orbits(gens, K):
    """orbits of the group generated by the permutations gens on range(K)"""
    seen = [False] * K; orbs = []
    for x in range(K):
        if seen[x]: continue
        o = [x]; seen[x] = True; i = 0
        while i < len(o):
            y = o[i]; i += 1
            for g in gens:
                z = g[y]
                if not seen[z]: seen[z] = True; o.append(z)
        orbs.append(sorted(o))
    return orbs

def sigma_groups(a, qorbmax):
    """generators (as permutations of Q = Z_2^a, element = integer with block bits) of the groups described above,
    deduplicated by their orbit partition of Q; each item: (label, gens on Q, gens on characters)"""
    K = 1 << a; out = []; seen = set()
    for parts in partitions(a):
        offs = [sum(parts[:i]) for i in range(len(parts))]
        blocks = [(d, o) for d, o in zip(parts, offs) if d >= 2]
        if not blocks: continue
        gen = {d: gf_gen(d) for d, _ in blocks}
        # subgroup orders per block
        choices = [[c for c in range(1, (1 << d)) if ((1 << d) - 1) % c == 0] for d, _ in blocks]
        def block_map(i, c, j=1):
            """permutation of Q: multiplication by h^j on block i, h of order c"""
            d, o = blocks[i]; h = gf_pow(gen[d], ((1 << d) - 1) // c, d); hj = gf_pow(h, j, d)
            img = []
            for q in range(K):
                v = (q >> o) & ((1 << d) - 1)
                img.append((q & ~(((1 << d) - 1) << o)) | (gf_mul(v, hj, d) << o))
            return img
        for cs in itertools.product(*choices):
            if all(c == 1 for c in cs): continue
            # product group
            gens = [block_map(i, c) for i, c in enumerate(cs) if c > 1]
            cands = [('prod', parts, cs, None, gens)]
            # cyclic diagonals (h_1, h_2^j2, ...), j coprime to the order of the block
            nz = [i for i, c in enumerate(cs) if c > 1]
            if len(nz) >= 2:
                js = [[1]] + [[j for j in range(1, cs[i]) if math.gcd(j, cs[i]) == 1] for i in nz[1:]]
                for jj in itertools.product(*js):
                    img = list(range(K))
                    for i, j in zip(nz, jj):
                        m = block_map(i, cs[i], j); img = [m[x] for x in img]
                    cands.append(('diag', parts, cs, list(jj), [img]))
            for kind_, parts_, cs_, jj, gs in cands:
                orbs = group_orbits(gs, K)
                if len(orbs) > qorbmax: continue
                key = frozenset(frozenset(o) for o in orbs)
                if key in seen: continue
                seen.add(key)
                dg = [dual_perm(g, K) for g in gs]
                corbs = group_orbits(dg, K)
                assert len(corbs) == len(orbs)
                order = len(set(tuple(x) for x in _closure(gs, K)))
                out.append(dict(label=f'{kind_} {parts_} {list(cs_)}' + (f' j={jj}' if jj else ''), order=order,
                                qorbs=orbs, corbs=corbs))
    return out

def _closure(gens, K):
    ident = tuple(range(K)); S = {ident}; frontier = [ident]
    while frontier:
        nf = []
        for x in frontier:
            for g in gens:
                y = tuple(g[i] for i in x)
                if y not in S: S.add(y); nf.append(y)
        frontier = nf
        if len(S) > 5000: break
    return S

def sums_alphabet(sizes):
    vals = {0}
    for z in sizes: vals = {v + z for v in vals} | {v - z for v in vals}
    return sorted(vals)

# ---------------------------------------------------------------- G1
def g1_cell_energy(a, t, p, qsizes, Y):
    K = 1 << a; num = 4 * t * t + 4 * p * (K - t)
    if num % K: return False, 'non-integral'
    tgt = num // K
    reach = {0}
    sq = sorted({y * y for y in Y})
    for A in qsizes:                     # four cells per Sigma-orbit, each contributes |A| y^2
        for _ in range(4):
            reach = {r + A * v for r in reach for v in sq if r + A * v <= tgt}
    return tgt in reach, tgt

# ---------------------------------------------------------------- G2 (copy of fable_tcensus2.qlevel + row sums)
def qlevel_rows(P, Y, p, t, Torb, triv):
    N = P.shape[0]; n = 4 * p
    tgt = np.array([4 * t if i in Torb else n for i in range(N)], dtype=np.int64)
    Trows = sorted(Torb); lowb = int(math.isqrt(4 * t))
    Yv = np.array(Y, dtype=np.int64); h = N // 2
    if len(Y) ** (N - h) > 4_000_000 or len(Y) ** h > 4_000_000: return 'cap: block space', None
    GL = np.array(list(itertools.product(range(len(Y)), repeat=h)), dtype=np.int32).reshape(-1, h)
    GR = np.array(list(itertools.product(range(len(Y)), repeat=N - h)), dtype=np.int32).reshape(-1, N - h)
    VL = Yv[GL]; VR = Yv[GR]
    WL = VL @ P[:, :h].T; WR = VR @ P[:, h:].T
    dR = collections.defaultdict(list)
    TR = WR[:, Trows]
    for idx, kk in enumerate(map(bytes, TR.astype(np.int64))): dR[kk].append(idx)
    # box join [P: |yhat(i)| <= sqrt(4t) on T, so L + R lies in a box on the T-rows]: distinct right T-row keys are
    # tested against every left half at once (replaces the enumeration of offsets of fable_tcensus2.qlevel)
    keys = list(dR.keys())
    RK = np.array([np.frombuffer(k_, dtype=np.int64) for k_ in keys]).reshape(len(keys), len(Trows))
    noffs = (2 * lowb + 1) ** len(Trows)
    energies = set()
    if noffs * len(VL) <= 200_000_000 and noffs * len(VL) <= len(RK) * len(VL):
        # enumeration of offsets, as in fable_tcensus2.qlevel
        rng = range(-lowb, lowb + 1)
        offs = np.array(list(itertools.product(rng, repeat=len(Trows))), dtype=np.int64).reshape(-1, len(Trows))
        for il in range(len(VL)):
            for row in offs - WL[il, Trows][None, :]:
                lst = dR.get(row.tobytes())
                if not lst: continue
                W = WL[il][None, :] + WR[lst]; E = W * W
                for e in E[np.all(E <= tgt[None, :], axis=1)]: energies.add(e.tobytes())
                if len(energies) > 60000: return 'cap: more than 60000 block energy vectors', None
        VLloop = []
    else:
        if len(RK) * len(VL) > 3_000_000_000: return 'cap: box join', None
        VLloop = range(len(VL))
    LT = WL[:, Trows]
    CH = max(1, 2_000_000 // max(1, len(RK)))
    for c0 in range(0, len(VLloop), CH):
        Lc = LT[c0:c0 + CH]
        ok = np.all(np.abs(Lc[:, None, :] + RK[None, :, :]) <= lowb, axis=2)
        for il_, ik in zip(*np.nonzero(ok)):
            il = c0 + int(il_)
            lst = dR[keys[int(ik)]]
            W = WL[il][None, :] + WR[lst]
            E = W * W
            okE = np.all(E <= tgt[None, :], axis=1)
            for e in E[okE]: energies.add(e.tobytes())
            if len(energies) > 60000: return 'cap: more than 60000 block energy vectors', None
    if not energies: return 0, set()
    U = np.array([np.frombuffer(e, dtype=np.int64) for e in energies])
    pairs = collections.defaultdict(list)
    for i in range(len(U)):
        S2 = U[i][None, :] + U[i:]
        good = np.nonzero(np.all(S2 <= tgt[None, :], axis=1))[0]
        for jj in good: pairs[S2[jj].tobytes()].append((i, i + int(jj)))
        if len(pairs) > 5_000_000: return 'cap: pairs', None
    rows = set(); cnt = 0
    for kk, lst in pairs.items():
        comp = (tgt - np.frombuffer(kk, dtype=np.int64)).tobytes()
        if comp not in pairs or kk > comp: continue
        for (i, j) in lst:
            for (k2, l2) in pairs[comp]:
                cnt += 1
                rows.add(tuple(sorted(int(U[x][triv]) for x in (i, j, k2, l2))))
                if len(rows) > 20000: break
    return cnt, rows

# ---------------------------------------------------------------- G3
def slevel_rows(s, uorbs, W, p, t, triv_in_T, cap=2_000_000):
    """blocks w: values in W on the U-orbits of Z_s; sum_k PAF(w_k)(h) = F(h) on one lag per <U,-1>-orbit."""
    T0 = 4 * t if triv_in_T else 4 * p
    num = T0 - 4 * p
    if num % s: return 'non-integral', None
    Fh = num // s; F0 = (T0 + 4 * p * (s - 1)) // s
    assert (T0 + 4 * p * (s - 1)) % s == 0
    # lag classes: orbits of <U, -1> on Z_s \ 0
    orb_of = {}
    for i, o in enumerate(uorbs):
        for z in o: orb_of[z] = i
    lagreps = []; seenl = set()
    for i, o in enumerate(uorbs):
        z = o[0]
        if z == 0: continue
        key = frozenset(orb_of[z2] for z2 in (z, (-z) % s))
        if key in seenl: continue
        seenl.add(key); lagreps.append(z)
    R = len(uorbs); sizes = [len(o) for o in uorbs]
    # N_{ij}(h) = #{z in O_i : z + h in O_j}
    Nmat = np.zeros((len(lagreps), R, R), dtype=np.int64)
    for li, h in enumerate(lagreps):
        for i, o in enumerate(uorbs):
            for z in o: Nmat[li, i, orb_of[(z + h) % s]] += 1
    tgt = np.array([F0] + [Fh] * len(lagreps), dtype=np.int64)
    # enumerate blocks with energy <= F0 (DFS with energy pruning), modulo sign
    Wv = sorted(W, key=abs)
    blocks = []
    order = sorted(range(R), key=lambda i: -sizes[i])
    def rec(pos, cur, en):
        if len(blocks) > cap: return
        if pos == R:
            blocks.append(list(cur)); return
        i = order[pos]
        for w in Wv:
            e2 = en + sizes[i] * w * w
            if e2 > F0: break
            cur[i] = w; rec(pos + 1, cur, e2)
    rec(0, [0] * R, 0)
    if len(blocks) > cap: return 'cap: blocks', None
    if not blocks: return 0, set()
    B = np.array(blocks, dtype=np.int64)
    # sign normalisation: keep w with first nonzero coordinate > 0
    fnz = np.argmax(B != 0, axis=1); keep = B[np.arange(len(B)), fnz] > 0
    B = B[keep | np.all(B == 0, axis=1)]
    en = (B * B) @ np.array(sizes, dtype=np.int64)
    paf = np.einsum('bi,lij,bj->bl', B, Nmat, B)
    feat = np.concatenate([en[:, None], paf], axis=1)
    rowsum = B @ np.array(sizes, dtype=np.int64)
    if len(feat) > 30000: return 'cap: blocks for the join', None
    pairs = collections.defaultdict(list)
    for i in range(len(feat)):
        S2 = feat[i][None, :] + feat[i:]
        good = np.nonzero(S2[:, 0] <= F0)[0]
        for jj in good: pairs[S2[jj].tobytes()].append((i, i + int(jj)))
        if len(pairs) > 8_000_000: return 'cap: pairs', None
    rows = set(); cnt = 0
    for kk, lst in pairs.items():
        comp = (tgt - np.frombuffer(kk, dtype=np.int64)).tobytes()
        if comp not in pairs or kk > comp: continue
        for (i, j) in lst:
            for (k2, l2) in pairs[comp]:
                cnt += 1
                rows.add(tuple(sorted(int(rowsum[x]) ** 2 for x in (i, j, k2, l2))))
    return cnt, rows

# ---------------------------------------------------------------- driver
def char_matrix(a, qorbs, corbs):
    K = 1 << a
    chi = lambda m, q: 1 - 2 * (bin(m & q).count('1') & 1)
    return np.array([[sum(chi(co[0], q) for q in qo) for qo in qorbs] for co in corbs], dtype=np.int64)

REDO_CAPS = False

def run(primes, avals, rmax, qorbmax, outp, rmin=1, control=False):
    done = set()
    if os.path.exists(outp):
        for l in open(outp):
            try:
                r_ = json.loads(l)
                if REDO_CAPS and 'cap' in str(r_.get('gate')): continue
                done.add(r_['key'])
            except Exception: pass
    fo = open(outp, 'a')
    isprime = lambda m: m > 1 and all(m % d for d in range(2, int(m ** .5) + 1))
    for a in avals:
        K = 1 << a; t0 = time.time()
        groups = sigma_groups(a, qorbmax)
        print(f'a = {a}: {len(groups)} groups Sigma with at most {qorbmax} orbits ({time.time()-t0:.0f}s)', flush=True)
        for p in primes:
            t = p % K
            if t == 0: continue
            s = (p - t) // K
            if s < 2: continue
            sub = cyc_subgroups(s) if s > 2 else [(1, 1)]
            if (1, 1) not in sub and all(o != 1 for _, o in sub): sub = [(1, 1)] + sub
            for g in groups:
                rQ = len(g['qorbs']); qsizes = [len(o) for o in g['qorbs']]
                W = sums_alphabet(qsizes)
                # Sigma-invariant T of size t
                csz = [len(o) for o in g['corbs']]
                for sel in itertools.product((0, 1), repeat=len(csz)):
                    if sum(c for c, z in zip(csz, sel) if z) != t: continue
                    Torb = {i for i, z in enumerate(sel) if z}
                    T = sorted(m for i in Torb for m in g['corbs'][i])
                    knd = kind(T, K)
                    if control and knd != 'NEW': continue
                    triv = next(i for i, o in enumerate(g['corbs']) if 0 in o)
                    for (u, uo) in sub:
                        uorbs_sizes = zorbits(s, u) if s > 1 else [1]
                        rS = len(uorbs_sizes); r = rQ * rS
                        if r > rmax or r < rmin: continue
                        key = json.dumps([p, a, g['label'], T, s, u, uo])
                        if key in done: continue
                        rec = dict(key=key, p=p, a=a, sigma=g['label'], sigma_order=g['order'], qorbit_sizes=qsizes,
                                   T=T, t=t, kind=knd, s=s, U=[u, uo], r=r, rQ=rQ, rS=rS)
                        t1 = time.time()
                        if isprime(s) and s >= 5 and uo == s - 1:
                            rec['gate'] = 'axis'; rec['alive'] = False
                        else:
                            # U-orbits of Z_s
                            seen = [False] * s; uorbs = []
                            for z in range(s):
                                if seen[z]: continue
                                o = []; y = z
                                while not seen[y]:
                                    seen[y] = True; o.append(y); y = (y * u) % s
                                uorbs.append(o)
                            Y = sums_alphabet([len(o) for o in uorbs])
                            ok1, info1 = g1_cell_energy(a, t, p, qsizes, Y)
                            if not ok1:
                                rec['gate'] = f'G1 ({info1})'; rec['alive'] = False
                            else:
                                P = char_matrix(a, g['qorbs'], g['corbs'])
                                c2, rows2 = qlevel_rows(P, Y, p, t, Torb, triv)
                                rec['G2'] = c2 if not isinstance(c2, str) else c2
                                if isinstance(c2, str):
                                    rec['gate'] = f'G2 {c2}'; rec['alive'] = None
                                elif c2 == 0:
                                    rec['gate'] = 'G2'; rec['alive'] = False
                                else:
                                    c3, rows3 = slevel_rows(s, uorbs, W, p, t, triv in Torb)
                                    rec['G3'] = c3
                                    if isinstance(c3, str):
                                        rec['gate'] = f'G3 {c3}'; rec['alive'] = None
                                        rec['rows_G2'] = sorted(rows2)[:50]
                                    elif c3 == 0:
                                        rec['gate'] = 'G3'; rec['alive'] = False
                                    else:
                                        both = rows2 & rows3
                                        rec['rows_both'] = sorted(both)[:50]
                                        if not both:
                                            rec['gate'] = 'G4'; rec['alive'] = False
                                        else:
                                            rec['gate'] = 'passed'; rec['alive'] = True
                        rec['secs'] = round(time.time() - t1, 2)
                        fo.write(json.dumps(rec) + '\n'); fo.flush(); done.add(key)
                        if rec['alive'] is not False:
                            print(f"p={p} a={a} {g['label']} T={T} ({knd}) s={s} U={u}^{uo} r={r}: {rec['gate']} "
                                  f"G2={rec.get('G2')} G3={rec.get('G3')}", flush=True)
            print(f'  a={a} p={p} done ({time.time()-t0:.0f}s)', flush=True)

def main():
    global REDO_CAPS
    a_ = sys.argv[1:]
    REDO_CAPS = '--redo-caps' in a_
    get = lambda name, d: a_[a_.index(name) + 1] if name in a_ else d
    if '--control' in a_:
        # 599, a = 4, the groups of order 3 of fable_tcensus2 (r = 30 ... 114), non-classical T only
        run([599], [4], 120, 12, get('--out', 'logs/fable_fresh/tcensus3_control.jsonl'), rmin=30, control=True)
        return
    avals = [int(x) for x in get('--a', '4,5,6').split(',')]
    rmax = int(get('--rmax', '64')); qorbmax = int(get('--qorbmax', '12'))
    op = json.load(open('data/open_orders_lt10000.json'))['open']
    isprime = lambda m: m > 1 and all(m % d for d in range(2, int(m ** .5) + 1))
    primes = [n // 4 for n in op if n % 4 == 0 and isprime(n // 4)]
    if '--primes' in a_: primes = [int(x) for x in get('--primes', '').split(',')]
    run(primes, avals, rmax, qorbmax, get('--out', 'logs/fable_fresh/tcensus3.jsonl'))

if __name__ == '__main__':
    main()
