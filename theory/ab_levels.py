r"""Level budget of stage 2 for a GP-type slice and a stage-1 solution y [E, freedoms exact].

Levels are subgroups L of G' (characters of G' trivial on L, every nontrivial character of Z_q): C_L = lattice-Gaussian
bits of that level (theory/ab_gauss.stage2 with levels).  For the S/D split on the Z_2 axis 0 of G' (L = <e>, e the
generator of axis 0): per block and per G''-orbit the exact list of (pattern at (0,b), pattern at (1,b)) pairs and the
S value x(0,.) + x(1,.) on the fibre;  H_S = sum log2 (#distinct S values), h_D = sum E[log2 multiplicity] (the
D-freedom left once S is fixed, averaged over uniform configurations), H2 = sum log2 (#pairs).
Cost model of report/paley_523_answer.md 3: D_def = C(D|S) - h_D (S-solutions needed per core).
usage: python3 theory/ab_levels.py CFGJSON YFILE|core:PATH [--N 20000]"""
import sys, os, json, math, itertools
from collections import Counter
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ab_sweep as W, ab_gauss as AGs
from ab_s1sd import cfg_from_json


def subgroup_mask_axes(Gp, axes):
    """subgroup of G' generated by the unit vectors of the given axes"""
    m = np.ones(Gp.n, bool)
    for a in range(len(Gp.mods)):
        if a not in axes: m &= (Gp.co[:, a] == 0)
    return m


def sd_freedom(sl, Y):
    """exact S/D pair statistics for the Z_2 axis 0 of G'"""
    Gp = sl.Gp; n2 = Gp.n // 2
    H2 = 0.0; HS = 0.0; hD = 0.0
    for k in range(4):
        done = set()
        for j, bb in enumerate(sl.breps):
            b0 = int(bb) % n2  # element with axis-0 coordinate 0
            j0 = int(sl.borb[b0]); j1 = int(sl.borb[b0 + n2])
            key = (j0, j1)
            if key in done or (j1, j0) in done: continue
            done.add(key)
            P0, _ = AGs.fibre_patterns(sl, j0, int(Y[k, sl.breps[j0]]))
            P1, _ = AGs.fibre_patterns(sl, j1, int(Y[k, sl.breps[j1]]))
            # the fibre parts of j0 and j1 are matched by z-coordinate class: compare part sizes order
            # S value = per-part sums (parts of j0 and j1 are the M-classes in the same order)
            S = Counter()
            for p in P0:
                for q_ in P1: S[tuple((p + q_).tolist())] += 1
            tot = len(P0) * len(P1)
            H2 += math.log2(tot); HS += math.log2(len(S))
            hD += sum(c / tot * math.log2(c) for c in S.values())
    return dict(H2=round(H2, 2), H_S_distinct=round(HS, 2), h_D=round(hD, 2))


if __name__ == "__main__":
    a = sys.argv[1:]
    cfg = cfg_from_json(a[0]); sl = W.build(cfg)
    N = int(a[a.index('--N') + 1]) if '--N' in a else 20000
    src = a[1]
    if src.startswith('core:'):
        from ab_verify_published import load_core, recoordinate
        hdr, X0 = load_core(src[5:])
        mo = tuple(int(t) for t in hdr.split('group=')[1].split()[0].split('x'))
        amap = json.loads(a[a.index('--amap') + 1])
        X = recoordinate(X0, mo, cfg['mods'], amap)
        assert sl.is_invariant(X)
        Y = sl.compress(X)
    else:
        d = json.load(open(src)); Y = np.array(d['solutions'][0]['y'] if 'solutions' in d else d['y'])
    assert (sl.Gp.paf(Y).sum(0) == sl.T1).all()
    Gp = sl.Gp; nax = len(Gp.mods)
    levels = {'S(axis0)': subgroup_mask_axes(Gp, [0])}
    for ax in range(1, nax): levels[f'axis0+axis{ax}'] = subgroup_mask_axes(Gp, [0, ax])
    if nax > 2: levels['all but last'] = subgroup_mask_axes(Gp, list(range(nax - 1)))
    r = AGs.stage2(sl, Y, N=N, levels=levels)
    sd = sd_freedom(sl, Y)
    sd['H2_pairs'] = sd.pop('H2')
    out = dict(H2=r['H2'], C2=float(r['bits']), mahal=r.get('mahal'), stage2_log2E=float(r['stage2_log2E']),
               levels={k: v['bits'] if v['bits'] is None else float(v['bits']) for k, v in r['levels'].items()}, **sd)
    CS = out['levels']['S(axis0)']
    out['C_D_given_S'] = round(out['C2'] - CS, 2)
    out['D_def'] = round(out['C2'] - CS - sd['h_D'], 2)
    print(json.dumps(out))
