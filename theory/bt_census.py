class AutTable:
    """A finite group of permutations given as a list, with a multiplication table (index arithmetic)."""

    def __init__(self, perms):
        self.perms = [np.asarray(p, np.int64) for p in perms]
        self.n = len(perms)
        key = {p.tobytes(): i for i, p in enumerate(self.perms)}
        self.key = key
        self.mul = np.empty((self.n, self.n), np.int32)          # mul[a, b] = index of a o b (apply b then a)
        for a in range(self.n):
            for b in range(self.n):
                self.mul[a, b] = key[self.perms[a][self.perms[b]].tobytes()]
        self.fix = np.array([int((p == np.arange(len(p))).sum()) for p in self.perms])
        self.identity = key[np.arange(len(self.perms[0])).tobytes()]
        self.order = np.zeros(self.n, np.int64)
        for a in range(self.n):
            x, o = a, 1
            while x != self.identity:
                x = self.mul[a, x]; o += 1
            self.order[a] = o


def closure_pairs(TP, TO, gens):
    """subgroup of TP x TO generated by gens (list of (a, b) index pairs): frozenset of pairs"""
    S = {(TP.identity, TO.identity)}
    frontier = list(S)
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = (int(TP.mul[g[0], x[0]]), int(TO.mul[g[1], x[1]]))
            if y not in S:
                S.add(y); frontier.append(y)
    return frozenset(S)


def orbit_count(TP, TO, S):
    return sum(int(TP.fix[a]) * int(TO.fix[b]) for a, b in S) // len(S)


def enumerate_S(TP, TO, rmin, rmax, max_gens=2, verbose=False):
    """subgroups generated by <= max_gens elements of TP x TO with orbit count in [rmin, rmax].
    Returns list of (frozenset S, generators)."""
    els = [(a, b) for a in range(TP.n) for b in range(TO.n)]
    cyc = {}
    for g in els:
        S = closure_pairs(TP, TO, [g])
        if S not in cyc:
            cyc[S] = [g]
    res = {}
    for S, gens in cyc.items():
        r = orbit_count(TP, TO, S)
        if rmin <= r <= rmax:
            res[S] = gens
    if max_gens >= 2:
        cl = list(cyc.items())
        # joins of two cyclic subgroups (only those whose orbit count could be in range: r(S1) >= rmin needed since
        # orbit counts decrease when the group grows)
        cand = [(S, g) for S, g in cl if orbit_count(TP, TO, S) >= rmin]
        for i in range(len(cand)):
            for j in range(i + 1, len(cand)):
                S1, g1 = cand[i]; S2, g2 = cand[j]
                if S1 <= S2 or S2 <= S1:
                    continue
                S = closure_pairs(TP, TO, g1 + g2)
                if S in res or S in cyc:
                    continue
                r = orbit_count(TP, TO, S)
                if rmin <= r <= rmax:
                    res[S] = g1 + g2
    return list(res.items())


def conj_canonical(TP, TO, S, conjP=None):
    """canonical form of S under conjugation by the elements of TP (and TO, which is abelian here except GL)"""
    best = None
    rngP = range(TP.n) if conjP is None else conjP
    invP = {a: next(b for b in range(TP.n) if TP.mul[a, b] == TP.identity) for a in rngP}
    for c in rngP:
        ci = invP[c]
        img = tuple(sorted((int(TP.mul[TP.mul[c, a], ci]), b) for a, b in S))
        if best is None or img < best:
            best = img
    return best
