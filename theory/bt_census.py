def factorint(n):
    f = {}; d = 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def partitions(a, maxpart=None):
    if maxpart is None:
        maxpart = a
    if a == 0:
        yield ()
        return
    for p in range(min(a, maxpart), 0, -1):
        for rest in partitions(a - p, p):
            yield (p,) + rest


# ------------------------------------------------------------------------------------------------ 2-part
class TwoGroup:
    def __init__(self, exps):
        self.exps = tuple(sorted(exps))                     # e_1 <= ... <= e_k
        self.mods = tuple(2 ** e for e in self.exps)
        self.G = E.Grp(self.mods)
        self.k = len(self.mods)

    def n_endos(self):
        return 2 ** sum(min(a, b) for a in self.exps for b in self.exps)

    def endo_entries(self):
        """per entry (i, j): the allowed values of M_ij"""
        ent = []
        for i in range(self.k):
            row = []
            for j in range(self.k):
                ei, ej = self.exps[i], self.exps[j]
                step = 2 ** max(0, ei - ej)
                row.append(list(range(0, 2 ** ei, step)))
            ent.append(row)
        return ent

    def automorphisms(self, cap=2 ** 20):
        """all automorphism matrices (list of k x k arrays) and their permutations"""
        if self.k == 0:
            return [np.zeros((0, 0), np.int64)], [np.zeros(1, np.int64)]
        if self.n_endos() > cap:
            raise MemoryError(f"{self.n_endos()} endomorphisms")
        ent = self.endo_entries()
        flat = [ent[i][j] for i in range(self.k) for j in range(self.k)]
        G = self.G
        mats, perms = [], []
        # automorphism iff the images of the generators generate P, i.e. the map is injective: test via
        # reduction mod 2: M is an automorphism iff the induced map on P/2P ... (use a direct bijectivity test)
        for vals in itertools.product(*flat):
            M = np.array(vals, np.int64).reshape(self.k, self.k)
            P = G.idx(G.co @ M.T)
            if len(np.unique(P)) == G.n:
                mats.append(M); perms.append(P)
        return mats, perms

    def subgroups_of_index(self, q):
        """all subgroups of index q (as sorted element arrays)"""
        G = self.G
        target = G.n // q
        found = {}
        # generated by at most k elements; enumerate generating tuples of size <= k (small groups only)
        els = list(range(G.n))
        for r in range(0, self.k + 1):
            for gens in itertools.combinations(els[1:], r):
                H = G.subgroup(list(gens))
                if len(H) == target:
                    found[H.tobytes()] = H
        return list(found.values())


def quotient_type(G, H):
    """isomorphism type of G/H for |G/H| = 4: 'Z2^2' or 'Z4'"""
    # Z4 iff some element has order 4 modulo H
    Hs = set(H.tolist())
    for g in range(G.n):
        if int(G.idx(2 * G.co[g])) not in Hs:
            return 'Z4'
    return 'Z2^2'


# ------------------------------------------------------------------------------------------------ odd part
class OddPart:
    """O as a list of cyclic factors (with optional elementary Z_p^2 'E' handled as two equal factors and GL(2,p))."""

    def __init__(self, mods, gl_pairs=()):
        self.mods = tuple(mods)
        self.G = E.Grp(self.mods) if mods else E.Grp(())
        self.gl_pairs = tuple(gl_pairs)                    # index pairs (i, i+1) of equal prime factors with GL(2,p)

    def automorphisms(self):
        """list of matrices (diagonal units, or GL(2,p) blocks on gl_pairs)"""
        k = len(self.mods)
        blocks = []
        i = 0
        while i < k:
            if (i, i + 1) in self.gl_pairs:
                p = self.mods[i]
                mats = []
                for a, b, c, d in itertools.product(range(p), repeat=4):
                    if (a * d - b * c) % p:
                        mats.append(np.array([[a, b], [c, d]], np.int64))
                blocks.append(mats); i += 2
            else:
                m = self.mods[i]
                blocks.append([np.array([[u]], np.int64) for u in range(1, m) if math.gcd(u, m) == 1])
                i += 1
        out = []
        for combo in itertools.product(*blocks):
            out.append(E.block_diag(*combo) if combo else np.zeros((0, 0), np.int64))
        return out


