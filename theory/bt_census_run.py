r"""Census driver: every k = 4 structure (Q of order 4, T = its nontrivial characters) at the open orders n = 3 mod 4
with a symmetry group S generated by <= 2 elements of Aut(P)_{K_2} x Aut(O), up to conjugation by Aut(P)_{K_2}
[M: orbit counts, coset-Parseval, Q-level gate; E: Q-level stratified count read at the true target].

One JSON line per structure (restart-safe: structures already in OUT are skipped).
usage: python3 theory/bt_census_run.py OUT.jsonl --ns 839,863 [--rmin 8] [--rmax 160] [--N 1500] [--part i/W]
"""
import sys, os, json, math, time, argparse, itertools, hashlib
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bt_engine as E, bt_chain as C, bt_gates as BG, bt_census as BC


def odd_options(o):
    """odd parts of order o as cyclic factor tuples (+ GL pairs for squares of primes)"""
    f = BC.factorint(o)
    opts = [(tuple(sorted(p ** e for p, e in f.items())), ())]
    for p, e in f.items():
        if e == 2:
            mods = tuple(sorted([p, p] + [q ** k for q, k in f.items() if q != p]))
            i = mods.index(p)
            opts.append((mods, ((i, i + 1),)))
    return opts


def two_options(a, cap=2 ** 20, min_cap=0):
    """2-groups of order 2^a whose endomorphisms can be enumerated (min_cap < count <= cap), with their index-4
    subgroups up to Aut(P)"""
    out = []
    for part in BC.partitions(a):
        P = BC.TwoGroup(part)
        if P.n_endos() > cap or P.n_endos() <= min_cap:
            continue
        mats, perms = P.automorphisms(cap)
        K2s = P.subgroups_of_index(4)
        # classes under Aut(P)
        seen = set(); reps = []
        for K2 in K2s:
            k = K2.tobytes()
            if k in seen:
                continue
            reps.append(K2)
            for p in perms:
                seen.add(np.sort(p[K2]).tobytes())
        for K2 in reps:
            keep = [i for i, p in enumerate(perms) if set(p[K2].tolist()) == set(K2.tolist())]
            out.append(dict(P=P, K2=K2, Qtype=BC.quotient_type(P.G, K2),
                            mats=[mats[i] for i in keep], perms=[perms[i] for i in keep]))
    return out


def structures(n, rmin, rmax, t=3, cap=2 ** 20, min_cap=0):
    m = n - t
    a = 0
    while m % 2 == 0:
        m //= 2; a += 1
    for opt in two_options(a, cap=cap, min_cap=min_cap):
        P = opt['P']
        for omods, gl in odd_options(m):
            O = BC.OddPart(omods, gl)
            omats = O.automorphisms()
            operms = [O.G.perm_of(M) for M in omats] if omods else [np.zeros(1, np.int64)]
            if not omods:
                omats = [np.zeros((0, 0), np.int64)]
            TP = BC.AutTable(opt['perms']); TO = BC.AutTable(operms)
            res = BC.enumerate_S(TP, TO, rmin, rmax)
            seen = set()
            for S, gens in res:
                key = BC.conj_canonical(TP, TO, S)
                if key in seen:
                    continue
                seen.add(key)
                mods = P.mods + omods
                yield dict(n=n, P=P.exps, Pmods=P.mods, Omods=omods, Qtype=opt['Qtype'], K2=opt['K2'].tolist(),
                           gens=[(E.block_diag(opt['mats'][g[0]], omats[g[1]]) if omods else opt['mats'][g[0]]).tolist()
                                 for g in gens],
                           order=len(S), r=BC.orbit_count(TP, TO, S))


def build(rec):
    """BStruct from a census record"""
    Pmods, Omods = tuple(rec['Pmods']), tuple(rec['Omods'])
    mods = Pmods + Omods
    G = E.Grp(mods)
    PG = E.Grp(Pmods)
    # K = K2 x O: generators = K2 elements (as coordinates, padded) + unit vectors of O
    Kgens = []
    for g in rec['K2']:
        if g:
            Kgens.append(tuple(PG.co[g]) + (0,) * len(Omods))
    for j in range(len(Omods)):
        v = [0] * len(mods); v[len(Pmods) + j] = 1; Kgens.append(tuple(v))
    return E.BStruct(mods, Kgens, 'k', [np.array(M) for M in rec['gens']],
                     name=f"{rec['n']}:P{rec['Pmods']}:O{rec['Omods']}:S{rec['order']}")


def struct_key(rec):
    return hashlib.sha1(json.dumps([rec['n'], rec['Pmods'], rec['Omods'], rec['K2'], rec['gens']]).encode()).hexdigest()[:16]


def evaluate(rec, N=1200, maxq=3, maxtot=24, seed=1):
    t0 = time.time()
    st = build(rec)
    out = dict(rec)
    out['key'] = struct_key(rec)
    out['r'] = st.r[0]; out['e'] = st.e
    out['orbit_sizes'] = np.bincount(st.sizes[0]).nonzero()[0].tolist()
    cp = st.coset_parseval()
    out['cp_dead'] = any(d['dead'] for d in cp)
    out['cp'] = [(d['p'], round(d['margin'], 3)) for d in cp]
    out['inv_subgroups'] = [len(N) for N in st.invariant_subgroups()]
    if out['cp_dead']:
        out['verdict'] = 'no core [P] (coset-Parseval)'
        out['secs'] = round(time.time() - t0, 1)
        return out
    import bt_census2 as C2
    if len(st.Kel) > 1 and C2.alpha_trivial_on_K(st):
        out['verdict'] = 'no core [P] (Theorem alpha)'
        out['secs'] = round(time.time() - t0, 1)
        return out
    g = BG.Gates(st)
    try:
        qs = g.q_level()
    except MemoryError as e:
        out['verdict'] = f'Q-level cap ({e})'
        out['secs'] = round(time.time() - t0, 1)
        return out
    out['q_patterns'] = [list(map(int, q[0])) for q in qs]
    out['q_solutions'] = int(sum(len(q[1]) for q in qs))
    if not qs:
        out['verdict'] = 'no core [M] (Q-level empty)'
        out['secs'] = round(time.time() - t0, 1)
        return out
    # whole-structure lattice Gaussian (uniform orbit signs, no conditioning) for comparison [E]
    import q523_gauss as QG
    rng = np.random.default_rng(seed)
    V = np.zeros((N, st.ncls), np.int64)
    for i in range(4):
        X = rng.choice(np.array([-1, 1], np.int8), size=(N, st.r[i]))
        V += C.class_paf_orbits(st, i, X)
    gw = QG.gauss_bits(V, st.cls_target)
    out['log2E_whole'] = round(sum(st.r) - gw['bits'], 2) if np.isfinite(gw['bits']) else None
    out['whole_mahal'] = gw.get('mahal')
    # Q-level stratified count
    tot = 0.0; terms = []
    budget = maxtot
    for rows, sol, L in qs:
        w = BG.pattern_weight(tuple(abs(x) for x in rows)) if not st.split else 1
        idx = np.arange(len(sol))
        nq = max(1, min(maxq, budget // max(1, len(qs))))
        if len(idx) > nq:
            idx = rng.choice(len(sol), nq, replace=False)
        vals = []
        for k in idx:
            s = sol[k]
            zs = [L[i][0][s[i]] for i in range(4)]
            lm = sum(math.log2(L[i][1][s[i]]) for i in range(4))
            r = BG.stratified_bits(st, g.qQ, zs, N=N, seed=seed + int(k))
            vals.append(lm - r['bits'] if np.isfinite(r['bits']) else -math.inf)
            terms.append(dict(rows=list(map(int, rows)), log2E=round(vals[-1], 2), mahal=r.get('mahal'), rank=r.get('rank')))
        vals = np.array(vals)
        fin = vals[np.isfinite(vals)]
        if len(fin):
            tot += w * len(sol) * np.mean(2.0 ** (vals - 0)) if np.isfinite(vals).all() else w * len(sol) * np.mean(np.where(np.isfinite(vals), 2.0 ** vals, 0.0))
    out['log2E_Q'] = round(math.log2(tot), 2) if tot > 0 else None
    out['q_terms'] = sorted(terms, key=lambda d: -d['log2E'] if np.isfinite(d['log2E']) else 1e9)[:6]
    out['verdict'] = 'passes Q-level'
    out['secs'] = round(time.time() - t0, 1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--ns', default='599,719,751,839,863')
    ap.add_argument('--rmin', type=int, default=8)
    ap.add_argument('--rmax', type=int, default=160)
    ap.add_argument('--N', type=int, default=1500)
    ap.add_argument('--part', default='0/1')
    ap.add_argument('--list-only', action='store_true')
    ap.add_argument('--cap', type=float, default=2 ** 20, help='largest endomorphism count of the 2-part')
    ap.add_argument('--min-cap', type=float, default=0, help='only 2-parts with more endomorphisms than this')
    a = ap.parse_args()
    pi, pw = map(int, a.part.split('/'))
    done = set()
    import glob as _glob
    for fn in set([a.out] + _glob.glob(os.path.join(os.path.dirname(a.out) or '.', 'k4_P4_w*.jsonl'))):
        if os.path.exists(fn):
            for line in open(fn):
                try:
                    done.add(json.loads(line)['key'])
                except Exception:
                    pass
    k = 0
    for n in map(int, a.ns.split(',')):
        recs = list(structures(n, a.rmin, a.rmax, cap=int(a.cap), min_cap=int(a.min_cap)))
        print(f'n = {n}: {len(recs)} structures with {a.rmin} <= r <= {a.rmax}', flush=True)
        if a.list_only:
            continue
        for rec in recs:
            k += 1
            if (k - 1) % pw != pi:
                continue
            if struct_key(rec) in done:
                continue
            try:
                res = evaluate(rec, N=a.N)
            except Exception as e:
                res = dict(rec, key=struct_key(rec), verdict=f'error: {type(e).__name__}: {e}')
            with open(a.out, 'a') as f:
                f.write(json.dumps(res) + '\n')
            print(json.dumps({x: res.get(x) for x in ('n', 'Pmods', 'Omods', 'Qtype', 'order', 'r', 'e', 'verdict',
                                                     'q_solutions', 'log2E_Q', 'secs')}), flush=True)


if __name__ == '__main__':
    main()
