r"""Lattice-exact Gaussian estimator for sums of block contributions (used by theory/q523_levels.py) [E].

For integer sample vectors V_i (i = 1..N; each = the sum over the four blocks of a random configuration's signature),
the achievable values lie in V_1 + Lambda, Lambda = the lattice generated by the differences V_i - V_1 (computed exactly
by integer echelon reduction, python ints).  The probability that a uniform random configuration hits the target T is
estimated as  (density of the Gaussian fitted to the integer coordinates of V - V_1 in a basis of Lambda)  at the
coordinates of T - V_1.  If T - V_1 is not in Lambda the estimate is -inf (a parity obstruction, to be proved exactly
separately).  Using lattice coordinates removes the per-coordinate-gcd approximation and handles exact linear
relations (rank deficiency) automatically."""
import math
import numpy as np

def _egcd(a, b):
    x0, y0, x1, y1 = 1, 0, 0, 1
    while b:
        qt = a // b; a, b = b, a - qt * b; x0, x1 = x1, x0 - qt * x1; y0, y1 = y1, y0 - qt * y1
    return a, x0, y0

def echelon(rows):
    """Hermite normal form basis (rows, python ints; pivots positive, entries above pivots reduced) of the lattice
    spanned by rows, built incrementally so that entries stay small"""
    B = {}                                        # pivot column -> row
    for r in rows:
        v = list(map(int, r))
        changed = False
        while True:
            col = next((j for j, a in enumerate(v) if a), None)
            if col is None: break
            if col not in B:
                if v[col] < 0: v = [-a for a in v]
                B[col] = v; changed = True; break
            p = B[col]
            if v[col] % p[col] == 0:
                t = v[col] // p[col]; v = [a - t * b for a, b in zip(v, p)]; continue
            g, x, y = _egcd(p[col], v[col])                  # x p + y v has g at col; (v[col]/g) p - (p[col]/g) v has 0
            new = [x * a + y * b for a, b in zip(p, v)]
            rem = [(v[col] // g) * a - (p[col] // g) * b for a, b in zip(p, v)]
            if new[col] < 0: new = [-a for a in new]
            B[col] = new; v = rem; changed = True
        if not changed:                           # the row was in the lattice: B is unchanged and already reduced
            continue
        # reduce entries above pivots (keeps numbers small)
        cols = sorted(B)
        for i, c in enumerate(cols):
            for c2 in cols[:i]:
                rw = B[c2]; t = rw[c] // B[c][c]
                if t: B[c2] = [a - t * b for a, b in zip(rw, B[c])]
    piv = sorted(B)
    return [B[c] for c in piv], piv

def coords(basis, piv, v):
    """integer coordinates of v in the echelon basis, or None if v is not in the lattice"""
    v = list(map(int, v)); c = []
    for b, p in zip(basis, piv):
        if v[p] % b[p]: return None
        t = v[p] // b[p]; c.append(t)
        if t: v = [a - t * x for a, x in zip(v, b)]
    return c if not any(v) else None

def gauss_bits(V, T, nlat=400, ridge=0.0):
    """-log2 P(sum hits T) under the lattice-coordinate Gaussian; returns dict(bits, rank, in_lattice)"""
    V = np.asarray(V, np.int64); T = np.asarray(T, np.int64)
    D = (V[1:nlat + 1] - V[0]).tolist()
    while True:                                   # grow the lattice until every sample lies in it
        basis, piv = echelon(D)
        X = (V - V[0]).astype(np.int64); bad = np.zeros(len(V), bool)
        for i, p in enumerate(piv):
            b = np.array(basis[i], np.int64); off = (X[:, p] % b[p]) != 0
            bad |= off; t = np.where(off, 0, X[:, p] // b[p]); X -= t[:, None] * b[None, :]
        bad |= X.any(1)
        if not bad.any(): break
        D = basis + (V[np.nonzero(bad)[0][:50]] - V[0]).tolist()
    r = len(basis)
    if r == 0:
        return dict(bits=0.0 if (T == V[0]).all() else math.inf, rank=0, in_lattice=bool((T == V[0]).all()))
    ct = coords(basis, piv, (T - V[0]).tolist())
    if ct is None: return dict(bits=math.inf, rank=r, in_lattice=False)
    # coordinates of all samples (exact integer solve along pivots)
    B = np.array(basis, dtype=np.int64)
    C = np.zeros((V.shape[0], r), np.int64)
    X = (V - V[0]).astype(np.int64)
    for i, p in enumerate(piv):
        assert not (X[:, p] % B[i, p]).any(), "samples outside the difference lattice (increase nlat)"
        t = X[:, p] // B[i, p]
        C[:, i] = t
        X -= t[:, None] * B[i][None, :]
    assert not X.any(), "samples outside the difference lattice (increase nlat)"
    C = C.astype(np.float64)
    mu = C.mean(0); S = np.cov(C.T).reshape(r, r) + ridge * np.eye(r)
    w, U = np.linalg.eigh(S)
    if w.min() <= 1e-9 * max(w.max(), 1):
        return dict(bits=math.nan, rank=r, in_lattice=True, note="degenerate covariance")
    d = U.T @ (np.array(ct, float) - mu)
    lp = -0.5 * r * math.log(2 * math.pi) - 0.5 * np.log(w).sum() - 0.5 * (d * d / w).sum()
    return dict(bits=round(-lp / math.log(2), 2), rank=r, in_lattice=True,
                mahal=round(float(np.sqrt((d * d / w).sum())), 2))
