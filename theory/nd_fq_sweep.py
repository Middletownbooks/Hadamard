r"""All-subgroup b = 1 slice sweep for the non-cyclic groups G = Z_F x F_q (q = p^2), the analogue of
theory/p571_msweep.py for orders with v - 1 = F p^2 (883: Z_18 x F_49; 751: Z_30 x F_25; F_9 cases) [E].

Multiplier groups: subgroups M of Z_F^* x F_q^* (acting by (g, z) -> (u g, a z)), generated by at most two elements.
For each M with 16..90 orbits per block: orbits, equations (orbits of <M, -1> on G minus 0), and the whole-slice
Gaussian log2E = log2 #(configurations with rows (2,0,0,0), exact orbit-weighted counts) + 3 - bits, where bits is the
lattice-coordinate Gaussian of theory/q523_gauss.py for the summed PAF at one lag per equation orbit (full-group FFT).
Also reported: whether M fixes Z_F pointwise and the index s of its image in F_q^* (GP slices).
usage: python3 theory/nd_fq_sweep.py F p [--omin 16] [--omax 90] [--N 6000] [--only u,e]"""
import sys, os, json, math, itertools
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from q523_gauss import gauss_bits
from p571_slicelib import RowSumSampler
from nd_fq import Fq

class Group:
    def __init__(self, F, p):
        self.F, self.p = F, p; self.K = Fq(p); q = p * p; self.q = q; self.n = F * q
        self.UF = [u for u in range(1, F) if math.gcd(u, F) == 1] if F > 1 else [0]
        # element index: g * q + z
    def act(self, u, e):
        """permutation of G for (g, z) -> (u g, gamma^e z)"""
        F, q = self.F, self.q; K = self.K
        a = 1
        for _ in range(e % (q - 1)): a = int(K.mul[a, K.gen])
        g = np.repeat(np.arange(F), q); z = np.tile(np.arange(q), F)
        return ((u * g) % F) * q + K.mul[a, z]
    def neg(self):
        F, q = self.F, self.q
        g = np.repeat(np.arange(F), q); z = np.tile(np.arange(q), F)
        return ((-g) % F) * q + self.K.neg[z]

def closure(perms, n):
    """the permutation group generated by perms (as a list of index arrays)"""
    ident = np.arange(n); G = {ident.tobytes(): ident}; frontier = [ident]
    while frontier:
        nf = []
        for x in frontier:
            for pm in perms:
                y = pm[x]
                k = y.tobytes()
                if k not in G: G[k] = y; nf.append(y)
        frontier = nf
    return list(G.values())

def orbits_of(G, n):
    lab = -np.ones(n, np.int64); orbs = []
    for x in range(n):
        if lab[x] >= 0: continue
        o = sorted({int(gp[x]) for gp in G}); lab[o] = len(orbs); orbs.append(o)
    return lab, orbs

def estimate(Gr, gens, N=6000, seed=1, omin=16, omax=90):
    n = Gr.n; perms = [Gr.act(u, e) for (u, e) in gens]
    M = closure(perms, n)
    lab, orbs = orbits_of(M, n)
    rec = dict(gens=[list(g) for g in gens], order=len(M), orbits=len(orbs))
    if not (omin <= len(orbs) <= omax): return rec
    ng = Gr.neg(); Mm = M + [ng[pm] for pm in M]
    llab, lorbs = orbits_of(Mm, n)
    reps = [o[0] for o in lorbs]                      # includes 0 (the zero element's orbit is {0})
    rec['equations'] = len(reps) - 1
    # fixes Z_F pointwise? image index in F_q^*
    rec['fixes_ZF'] = all(u % Gr.F == 1 % Gr.F for (u, e) in gens)
    es = [e % (Gr.q - 1) for (u, e) in gens]; gq = 0
    for e in es: gq = math.gcd(gq, e)
    rec['index_on_Fq'] = math.gcd(gq, Gr.q - 1) if gq else Gr.q - 1
    sizes = [len(o) for o in orbs]; rs = RowSumSampler(sizes); rng = np.random.default_rng(seed)
    rows = (2, 0, 0, 0); cnt = [rs.count(r) for r in rows]
    if any(c == 0 for c in cnt): rec.update(feasible=False); return rec
    shape = (Gr.F, Gr.p, Gr.p)
    zi = np.arange(Gr.q); a_ = zi % Gr.p; b_ = zi // Gr.p
    # index map from flattened (g*q + z) to (g, a, b) in the FFT array
    def to_arr(X):
        A = np.zeros((X.shape[0],) + shape)
        A[:, np.repeat(np.arange(Gr.F), Gr.q), np.tile(a_, Gr.F), np.tile(b_, Gr.F)] = X
        return A
    rg = np.repeat(np.arange(Gr.F), Gr.q)
    repg = np.array([r // Gr.q for r in reps]); repz = np.array([r % Gr.q for r in reps])
    V = np.zeros((N, len(reps)), np.int64); chunk = 400
    for st in range(0, N, chunk):
        c = min(chunk, N - st); acc = 0
        for r in rows:
            Lb = rs.sample(rng, r, c)
            X = Lb[:, lab].astype(np.float64)
            A = to_arr(X); fa = np.fft.fftn(A, axes=(1, 2, 3))
            acc = acc + np.fft.ifftn(fa * fa.conj(), axes=(1, 2, 3)).real
        V[st:st + c] = np.rint(acc[:, repg, repz % Gr.p, repz // Gr.p]).astype(np.int64)
    T = np.array([4 * n if r == 0 else -4 for r in reps], np.int64)
    gb = gauss_bits(V, T)
    lE = sum(math.log2(x) for x in cnt) + 3 - gb['bits'] if gb.get('in_lattice') else -math.inf
    rec.update(rowsum_bits=round(sum(math.log2(x) for x in cnt), 1), constraint_bits=gb.get('bits'), rank=gb.get('rank'),
               log2E=round(lE, 1))
    return rec

def subgroups(Gr):
    """subgroups of Z_F^* x Z_{q-1} generated by <= 2 elements (u, e), deduplicated by their element sets"""
    UF = Gr.UF; Q = Gr.q - 1
    def elems(gens):
        S = {(1 % Gr.F, 0)}; fr = [(1 % Gr.F, 0)]
        while fr:
            nf = []
            for (u, e) in fr:
                for (a, b) in gens:
                    x = ((u * a) % Gr.F, (e + b) % Q)
                    if x not in S: S.add(x); nf.append(x)
            fr = nf
        return frozenset(S)
    seen = {}
    allel = [(u, e) for u in UF for e in range(Q)]
    for g1 in allel:
        k = elems([g1])
        if k not in seen: seen[k] = [g1]
    one = list(seen.items())
    for (k1, g1), (k2, g2) in itertools.combinations(one, 2):
        k = elems(g1 + g2)
        if k not in seen: seen[k] = g1 + g2
    return seen

