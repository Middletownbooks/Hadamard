r"""Independent exact count of the cores of a small k = 4 structure (shares no code with the other theory/bt_* scripts) [M].

Structure: G = Z_{m_1} x ... x Z_{m_k} (first coordinate slowest), K given by generators, Q = G/K of order 4,
Gamma = 12 on K and -4 off K (T = the three nontrivial characters of Q), S generated by integer matrices acting on
coordinates.  A core is a quadruple (x_1, .., x_4) of S-invariant +-1 sequences on G with
sum_i PAF_i(g) = -Gamma(g + K) for g != 0.  Every block is enumerated over all 2^r orbit signs (r <= 24); the
quadruples are counted by a 2 + 2 join on the distinct PAF vectors of one block (with multiplicities), split by the
squared row sums, matching pair sums by a random 64-bit linear hash; two independent hashes must agree.
Counts ordered quadruples, all signs and orders.
usage: python3 theory/bt_brute_count.py RECORD.json   (keys: mods, Kgens, gens; or a census record with Pmods, Omods,
       K2, gens)
"""
import sys, json, itertools
import numpy as np


def main():
    rec = json.load(open(sys.argv[1]))
    if 'mods' in rec:
        mods, Kgens = rec['mods'], rec['Kgens']
    else:
        Pm, Om = rec['Pmods'], rec['Omods']
        mods = Pm + Om
        Pco = list(itertools.product(*[range(m) for m in Pm]))
        Kgens = [list(Pco[g]) + [0] * len(Om) for g in rec['K2'] if g]
        Kgens += [[0] * len(Pm) + [int(i == j) for i in range(len(Om))] for j in range(len(Om))]
    k = len(mods); n = int(np.prod(mods)); marr = np.array(mods)
    co = np.array(list(itertools.product(*[range(m) for m in mods])), dtype=np.int64)
    idx = lambda c: int(np.ravel_multi_index(tuple(np.mod(c, marr)), mods))
    # K, cosets
    K = {0}; fr = [0]
    while fr:
        x = fr.pop()
        for g in Kgens:
            y = idx(co[x] + np.array(g))
            if y not in K:
                K.add(y); fr.append(y)
    coset = -np.ones(n, np.int64); q = 0
    for g in range(n):
        if coset[g] < 0:
            for h in K:
                coset[idx(co[g] + co[h])] = q
            q += 1
    assert q == 4
    F = np.where(coset == coset[0], -12, 4).astype(np.int64); F[0] = 4 * n
    # orbits
    perms = [np.array([idx(np.array(M) @ co[g]) for g in range(n)]) for M in rec['gens']]
    orb = -np.ones(n, np.int64); r = 0
    for g in range(n):
        if orb[g] < 0:
            st = [g]; orb[g] = r
            while st:
                x = st.pop()
                for P in perms:
                    y = int(P[x])
                    if orb[y] < 0:
                        orb[y] = r; st.append(y)
            r += 1
    assert r <= 20, r
    assert r <= 24, r
    # distinct PAF vectors of one block (all 2^r orbit signs, FFT over G in chunks) with multiplicities
    ax = tuple(range(1, k + 1))
    parts = []
    for c0 in range(0, 2 ** r, 2 ** 15):
        ids = np.arange(c0, min(2 ** r, c0 + 2 ** 15))
        Eb = 1 - 2 * ((ids[:, None] >> np.arange(r)[None, :]) & 1)
        Xa = Eb[:, orb].astype(np.float64).reshape((-1,) + tuple(mods))
        Fh = np.fft.fftn(Xa, axes=ax)
        # ifft(|fft|^2)(d) = sum_g x(g) x(g - d) = PAF(d) for real sequences
        P = np.rint(np.fft.ifftn(np.abs(Fh) ** 2, axes=ax).real).astype(np.int64).reshape(len(ids), n)
        u, c = np.unique(P, axis=0, return_counts=True)
        parts.append((u, c))
    U = np.concatenate([p[0] for p in parts]); Cn = np.concatenate([p[1] for p in parts])
    V, inv = np.unique(U, axis=0, return_inverse=True)
    m = np.bincount(inv.ravel(), weights=Cn).astype(np.int64)
    assert m.sum() == 2 ** r
    s2 = V.sum(1)                                            # (row sum)^2
    res = []
    for seed in (1, 2):                                      # two independent 64-bit linear hashes must agree
        rng = np.random.default_rng(seed)
        R = rng.integers(-2 ** 62, 2 ** 62, size=n, dtype=np.int64)
        with np.errstate(over='ignore'):
            h = (V * R[None, :]).sum(1)                      # wraps mod 2^64 (linear)
            hF = int((F * R).sum())
        groups = {int(v): np.flatnonzero(s2 == v) for v in np.unique(s2)}

        def table(S):
            hs, ws = [], []
            for A, ga in groups.items():
                B = S - A
                if B not in groups:
                    continue
                gb = groups[B]
                with np.errstate(over='ignore'):
                    hh = (h[ga][:, None] + h[gb][None, :]).ravel()
                ww = (m[ga][:, None] * m[gb][None, :]).ravel()
                hs.append(hh); ws.append(ww)
            if not hs:
                return None
            hh = np.concatenate(hs); ww = np.concatenate(ws)
            o = np.argsort(hh, kind='stable'); hh = hh[o]; ww = ww[o]
            uq, st_ = np.unique(hh, return_index=True)
            return uq, np.add.reduceat(ww, st_)

        total = 0
        tot4 = 4 * n + int(F[1:].sum())                      # = sum_i (row sum_i)^2
        for S in sorted({int(a) + int(b) for a in groups for b in groups}):
            if S > tot4 - S:
                continue
            TL = table(S)
            TR = TL if S == tot4 - S else table(tot4 - S)
            if TL is None or TR is None:
                continue
            with np.errstate(over='ignore'):
                need = hF - TL[0]
            pos = np.searchsorted(TR[0], need)
            pos = np.minimum(pos, len(TR[0]) - 1)
            ok = TR[0][pos] == need
            cnt = int((TL[1][ok] * TR[1][pos[ok]]).sum())
            total += cnt if S == tot4 - S else 2 * cnt       # (left, right) and (right, left) orders
        res.append(total)
    print(json.dumps(dict(n_group=n, r=r, distinct_paf_vectors=int(len(V)), cores_ordered=res[0],
                          hashes_agree=res[0] == res[1])), flush=True)


if __name__ == '__main__':
    main()
