r"""General multiplier-slice toolkit for b = 1 GS cores on a cyclic group Z_m (571 work, report/paley_571_answer.md).

A slice is given by a multiplier group M <= (Z/m)^* (any subgroup, cyclic or not; it may act on every CRT factor).
Variables: one +-1 per M-orbit of Z_m and block (the Paley(p) + mult:mu slices of theory/paley_slices.py are the
special case M = {t : t = QR mod p, t in <mu> mod n'}).  Equations: sum_k PAF_k(h) = -4 at one lag h per orbit of
<M, -1> on Z_m \ 0 (PAF is symmetric and M-invariant), row sums (+-2, 0, 0, 0).

estimate(): Gaussian log2E with exact orbit-weighted row-sum counts (same conventions as theory/paley_slices.py:
lattice step per coordinate from sample gcds, covariance eigen-decomposition, profile multiplicity 4 x 2).
usage: python3 theory/p571_slicelib.py m gen1 [gen2 ...] [--N 20000] [--seed 1]"""
import sys, json, math
import numpy as np

def mgroup(m, gens):
    """closure of the multiplicative group generated by gens mod m"""
    G = {1}; frontier = [1]
    gens = [g % m for g in gens]
    while frontier:
        nf = []
        for x in frontier:
            for g in gens:
                y = x * g % m
                if y not in G: G.add(y); nf.append(y)
        frontier = nf
    return sorted(G)

def orbits(m, G):
    seen = np.zeros(m, bool); out = []
    for g in range(m):
        if seen[g]: continue
        o = sorted({g * t % m for t in G}); seen[o] = True; out.append(o)
    return out

def lag_reps(m, G):
    """one representative per orbit of <G, -1> on Z_m minus 0, with the orbit size"""
    Gm = set(G) | {(-t) % m for t in G}
    seen = np.zeros(m, bool); seen[0] = True; reps = []; sz = []
    for h in range(1, m):
        if seen[h]: continue
        o = {h * t % m for t in Gm}; seen[list(o)] = True; reps.append(h); sz.append(len(o))
    return reps, sz

class RowSumSampler:
    """uniform +-1 vectors x on orbits (sizes s) with sum_j s_j x_j = r: exact counts (python ints) and sampling"""
    def __init__(self, sizes):
        self.s = list(sizes); self.tot = sum(sizes); n = len(sizes); T = self.tot
        self.cnt = [None] * (n + 1)
        c = np.zeros(2 * T + 1, dtype=object); c[T] = 1; self.cnt[n] = c
        for i in range(n - 1, -1, -1):
            s = self.s[i]; nc = np.zeros(2 * T + 1, dtype=object)
            nc[s:] += c[:2 * T + 1 - s]          # x_i = +1: remaining target t - s reachable -> t reachable
            nc[:2 * T + 1 - s] += c[s:]          # x_i = -1
            self.cnt[i] = nc; c = nc
        self.fl = [np.array([float(x) for x in cc]) for cc in self.cnt]
    def count(self, r):
        T = self.tot
        return int(self.cnt[0][r + T]) if -T <= r <= T else 0
    def sample(self, rng, r, N):
        T = self.tot; t = np.full(N, r, np.int64); out = np.zeros((N, len(self.s)), np.int8)
        if self.count(r) == 0: return None
        for i, s in enumerate(self.s):
            cur = self.fl[i][t + T]
            tp = t - s; ok = (tp >= -T) & (tp <= T)
            plus = np.where(ok, self.fl[i + 1][np.clip(tp + T, 0, 2 * T)], 0.0)
            take = rng.random(N) * cur < plus
            out[:, i] = np.where(take, 1, -1); t = np.where(take, t - s, t + s)
        assert (t == 0).all()
        return out

def expand(lab, orbs, m):
    X = np.zeros((lab.shape[0], m), np.int8)
    for j, o in enumerate(orbs): X[:, o] = lab[:, [j]]
    return X

def paf_rows(X):
    F = np.fft.rfft(X.astype(np.float64), axis=1)
    return np.rint(np.fft.irfft(np.abs(F) ** 2, n=X.shape[1], axis=1)).astype(np.int64)

def gauss_logp(S, T):
    """-log2(Gaussian density at T x lattice cell) for integer sample vectors S (N, d); drops constant/duplicate coords"""
    cols, seen = [], {}
    for j in range(S.shape[1]):
        kk = S[:3000, j].tobytes()
        if kk in seen:
            if T[j] != T[seen[kk]]: return math.inf, 0
            continue
        if S[:, j].std() == 0:
            if S[0, j] != T[j]: return math.inf, 0
            continue
        seen[kk] = j; cols.append(j)
    S = S[:, cols].astype(float); T = np.asarray(T)[cols].astype(float)
    mu = S.mean(0); C = np.atleast_2d(np.cov(S.T)); w, V = np.linalg.eigh(C); kw = w > 1e-6 * w.max()
    pr = V.T @ (T - mu)
    if (~kw).any() and np.abs(pr[~kw]).max() > 1e-6 * max(1.0, np.abs(pr).max()): return math.inf, int(kw.sum())
    d = S - S[0]; steps = np.array([max(1, int(np.gcd.reduce(np.abs(d[:, j]).astype(np.int64)))) for j in range(S.shape[1])])
    if not all((T[j] - S[0, j]) % steps[j] == 0 for j in range(len(steps))): return math.inf, int(kw.sum())
    lp = (np.log(steps).sum() - 0.5 * kw.sum() * math.log(2 * math.pi) - 0.5 * np.log(w[kw]).sum()
          - 0.5 * (pr[kw] ** 2 / w[kw]).sum()) / math.log(2)
    return -lp, int(kw.sum())

def estimate(m, gens, N=20000, seed=1, rows=(2, 0, 0, 0)):
    """Gaussian log2E of b = 1 cores in the M-slice of Z_m (row-sum profile (+-2,0,0,0), 8 placements)"""
    G = mgroup(m, gens); orbs = orbits(m, G); sizes = [len(o) for o in orbs]
    reps, rsz = lag_reps(m, G)
    rs = RowSumSampler(sizes); rng = np.random.default_rng(seed)
    cnt = [rs.count(r) for r in rows]
    rec = dict(m=m, gens=list(gens), order=len(G), orbits=len(orbs), equations=len(reps), free_bits=4 * len(orbs))
    if any(c == 0 for c in cnt): rec.update(feasible=False); return rec
    S = sum(paf_rows(expand(rs.sample(rng, r, N), orbs, m))[:, reps] for r in rows)
    cb, eqs = gauss_logp(S, np.full(len(reps), -4))
    lE = sum(math.log2(c) for c in cnt) + math.log2(8) - cb
    rec.update(rowsum_bits=round(sum(math.log2(c) for c in cnt), 1), constraint_bits=round(cb, 1), eqs=eqs,
               log2E=round(lE, 1))
    return rec

