cfg = cfg_from_json('@logs/b599x4/cfg_599x4.json'); sl = W.build(cfg)
Gp = sl.Gp
def sub_mask(gens):
    # subgroup of G' generated by gens (G' coords)
    S = {0}; fr = [0]
    gi = [Gp.idx(np.array(g)) for g in gens]
    while fr:
        x = fr.pop()
        for g in gi:
            y = int(Gp.add(x, g))
            if y not in S: S.add(y); fr.append(y)
    m = np.zeros(Gp.n, bool); m[list(S)] = True; return m
cands = {
 'S': [(1,0,0)],
 'S+Q3': [(1,0,0),(0,1,0)],
 'S+3Z9': [(1,0,0),(0,0,3)],
 'S+(1,3)': [(1,0,0),(0,1,3)],
 'S+(1,6)': [(1,0,0),(0,1,6)],
 'S+Q3x3Z9': [(1,0,0),(0,1,0),(0,0,3)],
 'S+Z9': [(1,0,0),(0,0,1)],
 'S+(1,1)': [(1,0,0),(0,1,1)],
 'S+(2,1)': [(1,0,0),(0,2,1)],
 'S+all': [(1,0,0),(0,1,0),(0,0,1)],
}
masks = {k: sub_mask(v) for k, v in cands.items()}
for k, m in masks.items(): print(k, int(m.sum()))

def entropy_u(sl, Y, mask):
    """exact entropy of the u-part of the compression along the subgroup (mask on G'), per block, summed.
    u(g') = p - n on free points; compression: u_M(coset) = sum over coset elements"""
    cos, nC = AGs.subgroup_compress_index(Gp, mask)
    H = 0.0; Hd = 0.0
    for k in range(4):
        # per G'-orbit j: u values; orbit j contributes to cosets with multiplicity
        dist = {(): 1.0}  # we do DP over orbits, state = tuple of coset sums (dict coset->value)
        # build per-orbit contribution vectors
        state = Counter({tuple([0]*nC): 1})
        for j, bb in enumerate(sl.breps):
            y = int(Y[k, bb])
            if abs(y) != 1: continue
            el = np.nonzero(sl.borb == j)[0]
            vec = np.zeros(nC, np.int64); np.add.at(vec, cos[el], 1)
            new = Counter()
            for s, c in state.items():
                for uu in (2, -2):
                    t = tuple(int(a + uu * b) for a, b in zip(s, vec))
                    new[t] += c
            state = new
        tot = sum(state.values())
        H += -sum(c / tot * math.log2(c / tot) for c in state.values())
        Hd += math.log2(len(state))
    return H, Hd

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
Y = typical_y_sampler(sl, seed)()
r = level_bits(sl, Y, masks, N=int(sys.argv[2]) if len(sys.argv) > 2 else 4000, seed=seed)
sd = sd_freedom(sl, Y)
print(json.dumps(dict(seed=seed, H2=r['H2'], C2=r['C2'], sd=sd)))
HS, HSd = entropy_u(sl, Y, masks['S'])
CS = r['levels']['S']['bits']
print('H_S (exact u-entropy at S)', round(HS, 2), 'distinct', round(HSd, 2), 'C_S', CS, ' (H2-hD =', round(sd['H2']-sd['h_D'], 2), ')')
for k in masks:
    if k == 'S': continue
    HM, HMd = entropy_u(sl, Y, masks[k])
    CM = r['levels'][k]['bits']; rk = r['levels'][k]['rank']
    t1 = CS - HS + HM / 2; t2 = (CS - CM) - (HS - HM) / 2
    cost = math.log2(2 ** t1 + 2 ** t2)
    print(f"{k:12s} H_M {HM:6.2f} (distinct {HMd:6.2f})  C_M {CM}  rank {rk}  dense {CM - HM/2:+.2f}  per-S-sol 2^{cost:.2f}  (plain 2^{CS - HS/2:.2f})")
