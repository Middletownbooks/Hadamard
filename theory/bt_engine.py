r"""Structure engine for bordered Goethals-Seidel arrays with a character set T (Kumar, search/NOTES.md section 18;
[EKLO] Theorem 7 is T = all nontrivial characters) [P for the identities, M for the evaluations].

Setting.  G = Z_{m_1} x ... x Z_{m_k} (elements in mixed radix, FIRST factor slowest, as in Kumar's certificates),
K <= G of index q, Q = G/K, Gamma: Q -> Z with Gamma = 4 sum_{chi in T} chi (t = Gamma(0)/4).  Four +-1 sequences x_i on
G with

    sum_i PAF_{x_i}(g) = F(g),   F(0) = 4|G|,   F(g) = -Gamma(g + K)  (g != 0),

are completed by a border of 4t rows/columns to H(4n), n = |G| + t, when the border problem is solvable.  In
characters: sum_i |x^_i(psi)|^2 = 4t if psi = chi o pi with chi in T, and 4n otherwise.

Symmetry.  Block i is constant on the orbits of a group S_i of automorphisms of G (integer matrices M acting on
coordinate columns, g -> M g mod m; every S_i must preserve K and Gamma o pi).  PAF_i is constant on the orbits of
<S_i, -1>, so the equations are indexed by the classes of the meet of these partitions (one equation per class; the
class of 0 is lag 0).  With one common S this is the usual "orbits of <S, -1>".

Compression [P].  For any subgroup N, y_i(u) = sum_{g in u} x_i(g) on G/N satisfies sum_i PAF_{y_i} = F_N,
F_N(u) = sum_{g in u} F(g).  For N invariant under every S_i, y_i is constant on the S_i-orbits of G/N and every
S_i-orbit O of G maps onto one S_i-orbit U of G/N with |O|/|U| points over each point of U.

Coset-Parseval screen [P] (report/b599x4_answer.md section 1, adapted to T): N of prime order p, C_i the union of the
S_i-orbits O with O + N != O.  For chi with chi|_N != 1, x^_i(chi) = (x_i 1_{C_i})^(chi), and Parseval on G and G/N
gives sum_{chi|_N != 1} |x^_i(chi)|^2 <= |G| |C_i| (1 - 1/p^2) (p odd; C_i is a union of N-cosets with odd coset
sums) or <= |G| |C_i| (p = 2).  The targets need 4n |G| (1 - 1/p) - 4 |G| tau_N, tau_N = #{chi in T : chi
nontrivial on pi(N)}.  So no core when sum_i |C_i| (1 - 1/p^2) < 4 n (1 - 1/p) - 4 tau_N (p odd), resp.
sum_i |C_i| < 4 n (1 - 1/p) - 4 tau_N (p = 2).

Credit: the construction and the compression chain are Kumar's (Apache-2.0, github.com/vatskishan03/hadamard);
this code is new.
"""
import itertools, math
from functools import reduce
import numpy as np


# ------------------------------------------------------------------------------------------------ groups
class Grp:
    """G = Z_{m_1} x ... x Z_{m_k}, elements 0..n-1 in mixed radix with the FIRST coordinate slowest."""

    def __init__(self, mods):
        self.mods = tuple(int(m) for m in mods)
        self.k = len(self.mods)
        self.n = int(np.prod(self.mods)) if self.k else 1
        self.marr = np.array(self.mods, dtype=np.int64)
        self.co = np.array(np.unravel_index(np.arange(self.n), self.mods)).T.astype(np.int64) if self.k else \
            np.zeros((1, 0), np.int64)
        self._add = None

    def idx(self, c):
        c = np.asarray(c, dtype=np.int64) % self.marr
        return np.ravel_multi_index(tuple(np.moveaxis(c, -1, 0)), self.mods)

    @property
    def add(self):
        """n x n addition table (int32)."""
        if self._add is None:
            self._add = self.idx(self.co[:, None, :] + self.co[None, :, :]).astype(np.int32)
        return self._add

    def neg(self):
        return self.idx(-self.co)

    def perm_of(self, M):
        """Permutation of the endomorphism g -> M g (mod m); raises if not a well-defined automorphism."""
        M = np.array(M, dtype=np.int64)
        assert M.shape == (self.k, self.k), "matrix shape"
        for i in range(self.k):
            for j in range(self.k):
                assert (M[i, j] * self.mods[j]) % self.mods[i] == 0, f"M not well defined at ({i},{j})"
        P = self.idx(self.co @ M.T)
        assert len(np.unique(P)) == self.n, "M is not bijective"
        return P

    def subgroup(self, gens):
        """Sorted element array of the subgroup generated by gens (coordinate tuples or indices)."""
        g_idx = [int(self.idx(np.array(g))) if not np.isscalar(g) else int(g) for g in gens]
        A = self.add if self.n <= 6000 else None
        H = np.array([0], np.int64)
        for g in g_idx:
            mask = np.zeros(self.n, bool); mask[H] = True
            if mask[g]:
                continue
            parts = [H]; jg = g
            while not mask[jg]:
                parts.append(A[H, jg] if A is not None else self.idx(self.co[H] + self.co[jg]))
                jg = int(A[jg, g]) if A is not None else int(self.idx(self.co[jg] + self.co[g]))
            H = np.unique(np.concatenate(parts)).astype(np.int64)
        return H

    def order(self, g):
        c = self.co[g]
        return reduce(lambda a, b: a * b // math.gcd(a, b),
                      [self.mods[i] // math.gcd(int(c[i]), self.mods[i]) for i in range(self.k)], 1)


def perm_closure_orbits(n, perms):
    """Orbits of the group generated by permutations (arrays) on range(n): (orbit id per point, reps, sizes)."""
    parent = np.arange(n)

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]; a = parent[a]
        return a
    for P in perms:
        for a in range(n):
            ra, rb = find(a), find(int(P[a]))
            if ra != rb:
                parent[max(ra, rb)] = min(ra, rb)
    roots = np.array([find(a) for a in range(n)])
    reps, oid = np.unique(roots, return_inverse=True)
    sizes = np.bincount(oid)
    return oid.astype(np.int64), reps.astype(np.int64), sizes.astype(np.int64)


def meet_partition(labels_list):
    """Common refinement of partitions given as label arrays: new label per point (by first occurrence)."""
    key = np.stack(labels_list, axis=1)
    _, first, inv = np.unique(key, axis=0, return_index=True, return_inverse=True)
    order = np.argsort(first)                    # relabel classes by smallest element
    relabel = np.empty_like(order); relabel[order] = np.arange(len(order))
    return relabel[inv.ravel()]


def group_elements(perms, n, cap=200000):
    """All elements (as permutation arrays) of the group generated by perms (small groups only)."""
    I = np.arange(n)
    seen = {I.tobytes(): I}; frontier = [I]
    while frontier:
        x = frontier.pop()
        for P in perms:
            y = P[x]
            k = y.tobytes()
            if k not in seen:
                seen[k] = y; frontier.append(y)
                if len(seen) > cap:
                    raise RuntimeError("group too large")
    return list(seen.values())


# ------------------------------------------------------------------------------------------------ structure
class BStruct:
    """A bordered-GS structure: group, K, Gamma, per-block symmetry generators (integer matrices).

    mods      : cyclic factors of G
    Kgens     : generators of K (coordinate tuples)
    gamma     : dict coset-index -> Gamma value, or callable(coset_rep_coords) -> int, or 'k' (Gamma(0) = 4(q-1),
                Gamma = -4 elsewhere: T = all nontrivial characters, [EKLO] Theorem 7), or 'all' (Gamma = 4q delta_0)
    gens      : list of matrices (common S) or list of 4 lists (per-block S_i)
    """

    def __init__(self, mods, Kgens, gamma='k', gens=(), name=''):
        self.name = name
        self.G = G = Grp(mods)
        self.Kel = G.subgroup(Kgens) if len(Kgens) else np.array([0])
        self.Kmask = np.zeros(G.n, bool); self.Kmask[self.Kel] = True
        # cosets of K, numbered by smallest element (Kumar's convention)
        cos = -np.ones(G.n, np.int64); qn = 0
        for g in range(G.n):
            if cos[g] < 0:
                cos[G.idx(G.co[g] + G.co[self.Kel])] = qn; qn += 1
        self.coset, self.q = cos, qn
        self.coset_rep = np.array([np.flatnonzero(cos == c)[0] for c in range(qn)])
        if isinstance(gamma, str):
            if gamma == 'k':
                gv = np.full(qn, -4, np.int64); gv[0] = 4 * (qn - 1)
            elif gamma == 'all':
                gv = np.zeros(qn, np.int64); gv[0] = 4 * qn
            else:
                raise ValueError(gamma)
        elif callable(gamma):
            gv = np.array([int(gamma(G.co[self.coset_rep[c]])) for c in range(qn)], np.int64)
        else:
            gv = np.array([int(gamma[c]) for c in range(qn)], np.int64)
        assert gv[0] % 4 == 0
        self.gamma = gv
        self.t = int(gv[0] // 4)
        self.nH = G.n + self.t                     # the order of the Hadamard matrix is 4 nH
        self.F = -gv[cos]
        self.F[0] = 4 * G.n
        # per-block generators
        gens = list(gens)
        if len(gens) == 4 and all(isinstance(x, (list, tuple)) and (len(x) == 0 or np.array(x[0]).ndim == 2)
                                  for x in gens):
            self.bgens = [list(x) for x in gens]
        else:
            self.bgens = [list(gens)] * 4
        self.split = any(len(self.bgens[i]) != len(self.bgens[0]) or
                         any(not np.array_equal(np.array(a), np.array(b)) for a, b in zip(self.bgens[i], self.bgens[0]))
                         for i in range(4))
        self.bperms = [[G.perm_of(M) for M in bl] for bl in self.bgens]
        for bl in self.bperms:
            for P in bl:
                assert self.Kmask[P][self.Kmask].all(), "generator does not preserve K"
                assert (self.F[P] == self.F).all(), "generator does not preserve the target"
        self.orb, self.reps, self.sizes = [], [], []
        for bl in self.bperms:
            o, r, s = perm_closure_orbits(G.n, bl)
            self.orb.append(o); self.reps.append(r); self.sizes.append(s)
        self.r = [len(s) for s in self.sizes]
        neg = G.neg()
        labs = []
        for bl in self.bperms:
            o, _, _ = perm_closure_orbits(G.n, bl + [neg])
            labs.append(o)
        self.cls = meet_partition(labs)
        self.ncls = int(self.cls.max()) + 1
        self.cls_rep = np.array([np.flatnonzero(self.cls == c)[0] for c in range(self.ncls)])
        self.cls_size = np.bincount(self.cls)
        assert self.cls_rep[0] == 0
        self.e = self.ncls - 1                      # equations besides lag 0
        self.cls_target = self.F[self.cls_rep]

    # -------------------------------------------------------------------------- basic evaluation
    def expand(self, i, eps):
        """orbit signs (r_i,) -> sequence on G"""
        return np.asarray(eps, np.int64)[self.orb[i]]

    def paf(self, x):
        A = self.G.add
        return np.array([int(x @ x[A[:, g]]) for g in range(self.G.n)])

    def paf_classes(self, x):
        A = self.G.add
        return np.array([int(x @ x[A[:, g]]) for g in self.cls_rep])

    def check_core(self, xs):
        """exact check of the bordered condition on G for four +-1 sequences"""
        tot = sum(self.paf(np.asarray(x, np.int64)) for x in xs)
        return bool((tot == self.F).all())

    def summary(self):
        return dict(name=self.name, mods=self.G.mods, n=self.nH, m=self.G.n, q=self.q, t=self.t,
                    r=self.r, e=self.e, split=self.split)

    # -------------------------------------------------------------------------- subgroups
    def invariant_subgroups(self, maxn=None):
        """All subgroups N of G invariant under every block's generators (as sorted element arrays)."""
        if getattr(self, '_invsub', None) is not None:
            out = self._invsub
            return out if maxn is None else [N for N in out if len(N) <= maxn]
        G = self.G
        allp = [P for bl in self.bperms for P in bl]
        o_all, _, _ = perm_closure_orbits(G.n, allp)      # orbits of the group generated by all S_i
        seen = {}
        base = []
        done = np.zeros(int(o_all.max()) + 1, bool)
        for g in range(1, G.n):
            if done[o_all[g]]:
                continue
            done[o_all[g]] = True
            orbit = np.flatnonzero(o_all == o_all[g])
            N = G.subgroup(_small_gens(G, orbit))
            k = N.tobytes()
            if k not in seen:
                seen[k] = N; base.append(N)
        # joins (an invariant subgroup is generated by the orbits it contains)
        frontier = list(base)
        allN = dict(seen)
        while frontier:
            new = []
            for A in frontier:
                for B in base:
                    if len(np.setdiff1d(B, A, assume_unique=True)) == 0:
                        continue
                    C = G.subgroup(_small_gens(G, np.union1d(A, B)))
                    k = C.tobytes()
                    if k not in allN:
                        allN[k] = C; new.append(C)
            frontier = new
        out = [np.array([0])] + sorted(allN.values(), key=len)
        self._invsub = out
        if maxn is not None:
            out = [N for N in out if len(N) <= maxn]
        return out

    def prime_invariant_subgroups(self):
        """The invariant subgroups of prime order, without the join closure of invariant_subgroups: such an N is
        generated by the orbit of any of its nonzero elements, so it is an orbit-generated subgroup of prime order
        (same list and order as the prime-order members of invariant_subgroups())."""
        if getattr(self, '_invsub', None) is not None:
            return [N for N in self._invsub if is_prime(len(N))]
        G = self.G
        allp = [P for bl in self.bperms for P in bl]
        o_all, _, _ = perm_closure_orbits(G.n, allp)
        out, seen = [], set()
        done = np.zeros(int(o_all.max()) + 1, bool)
        for g in range(1, G.n):
            if done[o_all[g]]:
                continue
            done[o_all[g]] = True
            p = G.order(g)
            if not is_prime(p):
                continue
            cyc = np.unique(G.idx(np.arange(p)[:, None] * G.co[g][None, :]))      # <g>
            if not np.isin(np.flatnonzero(o_all == o_all[g]), cyc).all():
                continue                                                         # the orbit generates more
            if cyc.tobytes() not in seen:
                seen.add(cyc.tobytes()); out.append(cyc)
        return sorted(out, key=len)

    # -------------------------------------------------------------------------- quotient data
    def quotient(self, N):
        """Data of the compression to G/N: Quot object."""
        return Quot(self, N)

    # -------------------------------------------------------------------------- coset-Parseval
    def coset_parseval(self):
        """Screen every invariant (under all S_i) subgroup N of prime order.  Returns list of dicts; dead=True
        means no core [P]."""
        G = self.G
        res = []
        for N in self.prime_invariant_subgroups():
            p = len(N)
            Cs = []
            for i in range(4):
                o = self.orb[i]
                # orbit O is N-stable iff for every g in O, g + n in O (n a generator of N suffices)
                nn = int(N[1])
                shifted = G.idx(G.co + G.co[nn])
                stable_pts = o[shifted] == o
                st = np.ones(self.r[i], bool)
                np.logical_and.at(st, o, stable_pts)
                Cs.append(int(self.sizes[i][~st].sum()))
            # tau_N: characters chi in T nontrivial on pi(N): equivalently the T-part of the target that the
            # characters nontrivial on N carry.  Computed from Gamma: sum_{chi in T, chi|piN != 1} 1 =
            # t - #{chi in T trivial on pi(N)} = t - (1/|piN|) sum_{u in piN} Gamma(u)/4.
            piN = np.unique(self.coset[N])
            tau = self.t - int(round(sum(self.gamma[u] for u in piN) / 4 / len(piN)))
            need = 4 * self.nH * (1 - 1 / p) - 4 * tau
            have = sum(Cs) * ((1 - 1 / p ** 2) if p % 2 else 1.0)
            res.append(dict(p=p, N=[int(x) for x in N[:4]], C=Cs, tau=tau, have=have, need=need,
                            margin=need / have if have > 0 else float('inf'), dead=bool(have < need - 1e-9)))
        return res


def _small_gens(G, elems):
    """a small generating set of the subgroup generated by elems (greedy)"""
    gens = []; cur = np.array([0])
    for e in elems:
        if not np.isin(e, cur):
            gens.append(int(e)); cur = G.subgroup(gens)
    return gens


# ------------------------------------------------------------------------------------------------ quotients
class Quot:
    """Compression of a structure to Gbar = G/N (N invariant under every S_i).

    pi[g]            : coset index of g (0..nb-1, by smallest element; coset 0 = N)
    add              : Gbar addition table
    borb[i], bsize[i]: S_i-orbits on Gbar (reduced coordinates of block i)
    omap[i][O]       : Gbar-orbit of the G-orbit O; w[i][O] = |O|/|U|
    cls, cls_rep     : equation classes on Gbar (meet over blocks of <S_i, -1>-orbits)
    FN               : pushed-forward target per class
    """

    def __init__(self, st, N):
        G = st.G
        self.st, self.N = st, np.asarray(N)
        pi = -np.ones(G.n, np.int64); nb = 0
        for g in range(G.n):
            if pi[g] < 0:
                pi[G.idx(G.co[g] + G.co[self.N])] = nb; nb += 1
        self.pi, self.nb = pi, nb
        self.rep = np.array([np.flatnonzero(pi == c)[0] for c in range(nb)])
        A = G.add
        self.add = pi[A[np.ix_(self.rep, self.rep)]]
        negb = pi[G.neg()[self.rep]]
        self.FN = np.bincount(pi, weights=st.F, minlength=nb).astype(np.int64)
        self.borb, self.bsize, self.omap, self.w, self.breps = [], [], [], [], []
        labs = []
        for i in range(4):
            bp = [pi[P[self.rep]] for P in st.bperms[i]]
            o, r, s = perm_closure_orbits(nb, bp)
            self.borb.append(o); self.bsize.append(s); self.breps.append(r)
            om = o[pi[st.reps[i]]]
            self.omap.append(om)
            w = st.sizes[i] // s[om]
            assert (w * s[om] == st.sizes[i]).all()
            # check: every point of U receives the same count
            self.w.append(w)
            o2, _, _ = perm_closure_orbits(nb, bp + [negb])
            labs.append(o2)
        self.cls = meet_partition(labs)
        self.ncls = int(self.cls.max()) + 1
        self.cls_rep = np.array([np.flatnonzero(self.cls == c)[0] for c in range(self.ncls)])
        self.cls_target = self.FN[self.cls_rep]

    def compress(self, x):
        return np.bincount(self.pi, weights=x, minlength=self.nb).astype(np.int64)

    def paf_classes(self, y):
        """PAF of full Gbar-vectors y (... x nb) at the class representatives"""
        y = np.asarray(y, np.int64)
        return np.stack([(y * y[..., self.add[:, u]]).sum(-1) for u in self.cls_rep], axis=-1)

    def contrib(self, i):
        """contribution matrix (r_i x nbo_i) of block i: orbit O adds w_O to its Gbar-orbit coordinate"""
        r = self.st.r[i]; nbo = len(self.bsize[i])
        C = np.zeros((r, nbo), np.int64)
        C[np.arange(r), self.omap[i]] = self.w[i]
        return C

    def full_from_reduced(self, i, yred):
        return np.asarray(yred)[..., self.borb[i]]


# ------------------------------------------------------------------------------------------------ helpers
def is_prime(p):
    return p >= 2 and all(p % d for d in range(2, int(p ** 0.5) + 1))


def mult_matrix(mods, axis_mults):
    """Diagonal automorphism multiplying coordinate i by axis_mults[i] (must be a unit mod m_i)."""
    k = len(mods)
    M = np.zeros((k, k), np.int64)
    for i, u in enumerate(axis_mults):
        M[i, i] = u % mods[i]
    return M


def block_diag(*Ms):
    k = sum(np.array(M).shape[0] for M in Ms)
    out = np.zeros((k, k), np.int64); o = 0
    for M in Ms:
        M = np.array(M); s = M.shape[0]
        out[o:o + s, o:o + s] = M; o += s
    return out


ALPHA = np.array([[0, 1], [1, 1]])                 # order-3 automorphism of Z_2^2 (Kumar's 3964 sigma)
BETA = np.array([[0, 3], [1, 3]])                  # order-3 automorphism of Z_4^2 (Kumar's 2636 sigma)


def control_3964():
    mods = (2, 2, 247)
    s = block_diag(ALPHA, [[66]]); t = block_diag(np.eye(2, dtype=int), [[35]])
    return BStruct(mods, [(0, 0, 1)], 'k', [s, t], name='3964')


def control_2636():
    mods = (4, 4, 41)
    s = block_diag(BETA, [[1]]); t = block_diag(np.eye(2, dtype=int), [[10]])
    return BStruct(mods, [(2, 0, 0), (0, 2, 0), (0, 0, 1)], 'k', [s, t], name='2636')


