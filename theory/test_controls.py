"""Positive controls for slicesolve + certify: LP at small lengths, b1 over non-cyclic groups, b0 small."""
import sys, time
import numpy as np
from abgroup import AbGroup, AutGroup
from slicesolve import prepare, solve
from certify import build, verify

def run(comps, gens_fn, kind, label):
    G = AbGroup(comps); A = AutGroup(G)
    auts = gens_fn(A)
    P = prepare(G, [A.to_aut(x) for x in auts])
    sols, info = solve(P, kind, max_solutions=3, verbose=False)
    okc = None
    if sols:
        H = build(G, kind, sols[0]); okc = verify(H) if H is not None else False
    print(f'{label:40s} G={G} r={P["r"]} L={len(P["lrep"])} surv={info["survivors"]} sols={len(sols)} certified={okc} {info["secs"]}s', flush=True)
    return len(sols), okc

def unit_gen(A, comp_index, u):
    """automorphism that is the unit u on component comp_index, identity elsewhere"""
    x = list(A.ident()); els = A.parts[comp_index][0]; x[comp_index] = els.index(u); return [tuple(x)]

