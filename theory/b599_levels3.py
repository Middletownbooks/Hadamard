r"""Nested middle levels for the stage-2 S-join of a GP slice: exact entropies and Gaussian constraints [E, H exact].

Stage 2 (theory/ab_stage2.py): S/D on axis 0 of G'; the S-level is the compression along Z_2 (characters trivial on
axis 0).  A middle level M_L inside S: characters trivial on Z_2 x L for a U-stable subgroup L of G''.  For a y (a
stage-1 solution or a typical y), under uniform x with compression y:
  H_S = entropy of the S-image (sum over G''-orbits of the entropy of p0 + p1, p_e the fibre pattern of layer e);
  H_M = entropy of the M-image: per U-orbit of L-cosets c, the entropy of sum_o m(o, c) (p0 + p1)_o (exact
        convolution of the per-orbit S-value distributions; m(o, c) = elements of orbit o in coset c);
  C_S, C_M = lattice-Gaussian bits of the S- and M-levels (ab_typical_levels.level_bits).
Cost per S-solution (4-list 2 + 2 joins): plain 2^(C_S - H_S/2); with M as a separate level
  2^(C_S - H_S + H_M/2) [M-solutions, amortised] + 2^((C_S - C_M) - (H_S - H_M)/2) [fibre join per M-solution];
cost per core = 2^D_def x (cost per S-solution + 2^(h_D/2) D-check), D_def = C(D|S) - h_D.
usage: python3 theory/b599_levels3.py 'CFGJSON' [--seed 3] [--N 4000]"""
import sys, os, json, math, itertools
from collections import defaultdict, Counter
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ab_sweep as W, ab_gauss as AGs
from ab_s1sd import cfg_from_json
from ab_typical_levels import typical_y_sampler, level_bits
from ab_levels import sd_freedom


def ent(c):
    tot = sum(c.values())
    return -sum(v / tot * math.log2(v / tot) for v in c.values())


def conv(A, B, mA=1, mB=1):
    """distribution of mA*a + mB*b (vectors as tuples) for independent a ~ A, b ~ B"""
    out = Counter()
    for a, wa in A.items():
        for b, wb in B.items():
            out[tuple(mA * x + mB * y for x, y in zip(a, b))] += wa * wb
    return out


def sub_mask(Gp, gens):
    """subgroup of G' generated by the given elements (coordinate tuples)"""
    S = {tuple([0] * len(Gp.mods))}; fr = list(S); M = np.array(Gp.mods)
    while fr:
        x = fr.pop()
        for g in gens:
            y = tuple(((np.array(x) + np.array(g)) % M).tolist())
            if y not in S: S.add(y); fr.append(y)
    m = np.zeros(Gp.n, bool); m[Gp.idx(np.array(sorted(S)))] = True
    return m


def analyse(cfg, seed=3, N=4000, Ls=None):
    sl = W.build(cfg); Gp = sl.Gp; n2 = Gp.n // 2
    Y = typical_y_sampler(sl, seed)()
    # per block, per G'-orbit: S-value distributions over G''-orbits
    # G''-orbit of a G' element (e, h): pair (orbit of (0,h), orbit of (1,h))
    pats = {}
    for k in range(4):
        for j, bb in enumerate(sl.breps):
            P, _ = AGs.fibre_patterns(sl, j, int(Y[k, bb]))
            pats[(k, j)] = P
    Sdist = {}
    for k in range(4):
        for h in range(n2):
            j0 = int(sl.borb[h]); j1 = int(sl.borb[h + n2])
            key = (k, j0, j1)
            if key in Sdist: continue
            c = Counter()
            for p0 in pats[(k, j0)]:
                for p1 in pats[(k, j1)]: c[tuple((p0.astype(int) + p1.astype(int)).tolist())] += 1
            Sdist[key] = c
    # U on G'' (as G' elements with e = 0)
    Up = [Gp.act(u) for u in sl.Sp]
    # H_S: one term per G''-orbit (h up to U)
    seen = set(); HS = 0.0
    for k in range(4):
        for h in range(n2):
            o = min(int(P[h]) for P in Up)
            if (k, o) in seen: continue
            seen.add((k, o))
            HS += ent(Sdist[(k, int(sl.borb[h]), int(sl.borb[h + n2]))])
    out = dict(seed=seed, H_S_exact=round(HS, 2))
    # levels
    nax = len(Gp.mods)
    e = [tuple(1 if i == a else 0 for i in range(nax)) for a in range(nax)]
    if Ls is None:
        Ls = {}
        for a in range(1, nax): Ls[f'L=<e{a}>'] = [e[a]]
        for a in range(1, nax):
            for b in range(a + 1, nax): Ls[f'L=<e{a},e{b}>'] = [e[a], e[b]]
    levels = {'S': sub_mask(Gp, [e[0]])}
    for name, gens in Ls.items(): levels[name] = sub_mask(Gp, [e[0]] + list(gens))
    r = level_bits(sl, Y, levels, N=N, seed=seed)
    sd = sd_freedom(sl, Y)
    C2 = r['C2']; CS = r['levels']['S']['bits']; hD = sd['h_D']; H2 = r['H2']
    HSm = H2 - hD
    Ddef = C2 - CS - hD
    out.update(H2=H2, C2=C2, C_S=CS, h_D=hD, H_S=round(HSm, 2), D_def=round(Ddef, 2),
               plain_cost=round(Ddef + CS - HSm / 2, 2))
    # H_M per level: U-orbits of L-cosets of G'' (elements with e = 0)
    res = {}
    for name, gens in Ls.items():
        Lm = sub_mask(Gp, list(gens))                       # L inside G'' (e = 0)
        Lel = np.nonzero(Lm)[0]
        cos = -np.ones(n2, np.int64); ncos = 0
        for h in range(n2):
            if cos[h] >= 0: continue
            for l in Lel: cos[int(Gp.add(h, int(l)))] = ncos
            ncos += 1
        # U-orbits of cosets
        corb = {}
        for c in range(ncos):
            h = int(np.nonzero(cos == c)[0][0])
            imgs = {int(cos[int(P[h])]) for P in Up}
            corb[c] = min(imgs)
        HM = 0.0
        for k in range(4):
            for c in sorted(set(corb.values())):
                els = np.nonzero(cos == c)[0]
                # G''-orbits in this coset with multiplicities
                mult = Counter()
                for h in els: mult[(int(sl.borb[h]), int(sl.borb[h + n2]))] += 1
                dist = Counter({tuple([0] * 3): 1})
                for (j0, j1), m in mult.items():
                    dist = conv(dist, Sdist[(k, j0, j1)], 1, m)
                    if len(dist) > 4 * 10 ** 6: raise RuntimeError("distribution too large")
                HM += ent(dist)
        CM = r['levels'][name]['bits']
        t1 = CS - HSm + HM / 2; t2 = (CS - CM) - (HSm - HM) / 2
        per = math.log2(2 ** t1 + 2 ** t2)
        res[name] = dict(H_M=round(HM, 2), C_M=CM, rank=r['levels'][name]['rank'], cosets=ncos,
                         per_S_solution=round(per, 2), cost_per_core=round(Ddef + math.log2(2 ** per + 2 ** (hD / 2)), 2))
    out['levels'] = res
    return out


if __name__ == "__main__":
    a = sys.argv[1:]
    opt = lambda k, d: a[a.index(k) + 1] if k in a else d
    cfg = cfg_from_json(a[0])
    print(json.dumps(analyse(cfg, int(opt('--seed', '3')), int(opt('--N', '4000')))))
