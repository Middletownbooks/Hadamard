#!/bin/bash
# exhaustive high-symmetry slices: b0 over Z_v (squarefree -> product of prime cyclics), b1 over cyclic Z_{v-1}
R=${1:-30}
declare -A B0=( [523]="[('C',523)]" [537]="[('C',3),('C',179)]" [571]="[('C',571)]" [573]="[('C',3),('C',191)]" [599]="[('C',599)]" [643]="[('C',643)]" [647]="[('C',647)]" [659]="[('C',659)]" [669]="[('C',3),('C',223)]" [719]="[('C',719)]" [739]="[('C',739)]" )
declare -A B1=( [523]="[('C',2),('C',9),('C',29)]" [537]="[('C',8),('C',67)]" [571]="[('C',2),('C',3),('C',5),('C',19)]" [573]="[('C',4),('C',11),('C',13)]" [599]="[('C',2),('C',13),('C',23)]" [643]="[('C',2),('C',3),('C',107)]" [647]="[('C',2),('C',17),('C',19)]" [659]="[('C',2),('C',7),('C',47)]" [669]="[('C',4),('C',167)]" [719]="[('C',2),('C',359)]" [739]="[('C',2),('C',9),('C',41)]" )
for v in 523 537 571 573 599 643 647 659 669 719 739; do
  echo "### b0 v=$v"; python3 sweep_b1.py "${B0[$v]}" $R b0
  echo "### b1 v=$v (cyclic m=v-1)"; python3 sweep_b1.py "${B1[$v]}" $R b1
done
