r"""GP slices whose slice group also acts on Q by an automorphism (c = 4: the order-3 automorphism of Z_2^2;
c = 8: the order-7 Singer cycle of Z_2^3, as in 359's border), with multipliers on H' and the index-s subgroup on Z_q
[P for the construction; E/M as tagged where used].

The slice group is generated by permutations of G = Q x H' x Z_q (automorphisms fixing 0 that preserve Q x {0},
hence the target T); PermSlice provides the attributes of ab_lib.Slice that the Gaussians (ab_gauss.whole,
stage2_sampled), the direct stage-1 enumerator (ab_b0_stage1.stage1) and the exact stage-2 join
(ab_small_exact.solve_y) use.
usage: python3 theory/ab_qaut.py --scan [--vs 719,863,...] [--cs 4,8] [--N 4000] [--out FILE]"""
import sys, os, json, math, itertools, time
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ab_lib import AG, target, factorint
from ab_sweep import mgen, abelian_types, unit_subgroup_gens


def perm_closure(gens, n):
    I = tuple(range(n)); S = {I}; frontier = [I]
    gens = [tuple(int(x) for x in g) for g in gens]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = tuple(g[i] for i in x)            # composition g o x
            if y not in S: S.add(y); frontier.append(y)
    return [np.array(p, np.int64) for p in sorted(S)]


class PermSlice:
    def __init__(s, mods, v, b, gens, qaxis, Hmask=None):
        s.G = AG(mods); s.v, s.b = v, b; G = s.G
        s.perms = perm_closure(gens, G.n)
        s.Hmask = Hmask; s.T = target(G, v, b, Hmask)
        for P in s.perms:
            assert (s.T[P] == s.T).all(), "slice group does not preserve T"
            # automorphism check on a few pairs
            for a_, b_ in ((1, 2), (G.n // 3, G.n // 2)):
                assert P[G.add(a_ % G.n, b_ % G.n)] == G.add(P[a_ % G.n], P[b_ % G.n])
        orb = -np.ones(G.n, np.int64); reps = []; sizes = []
        for g in range(G.n):
            if orb[g] >= 0: continue
            img = {int(P[g]) for P in s.perms}
            for x in img: orb[x] = len(reps)
            reps.append(g); sizes.append(len(img))
        s.orb, s.reps, s.sizes, s.r = orb, reps, np.array(sizes), len(reps)
        s.qaxis = qaxis; s.q = G.mods[qaxis]
        s.Gp = AG(tuple(n for i, n in enumerate(G.mods) if i != qaxis))
        s.bco = np.delete(G.co, qaxis, axis=1); s.zco = G.co[:, qaxis]
        s.bidx = s.Gp.idx(s.bco) if len(s.Gp.mods) else np.zeros(G.n, np.int64)
        # induced permutations on G' (every generator maps fibres to fibres)
        s.Sp_perms = []
        for P in s.perms:
            Pp = -np.ones(s.Gp.n, np.int64)
            for g in range(G.n):
                b0, b1 = s.bidx[g], s.bidx[P[g]]
                assert Pp[b0] in (-1, b1); Pp[b0] = b1
            s.Sp_perms.append(Pp)
        borb = -np.ones(s.Gp.n, np.int64); breps = []
        for bb in range(s.Gp.n):
            if borb[bb] >= 0: continue
            img = {int(P[bb]) for P in s.Sp_perms}
            for x in img: borb[x] = len(breps)
            breps.append(bb)
        s.borb, s.breps, s.bsz = borb, breps, np.bincount(borb)
        s.parts = []
        for bb in breps:
            P_ = {}
            for g in np.nonzero(s.bidx == bb)[0]: P_[int(orb[g])] = P_.get(int(orb[g]), 0) + 1
            s.parts.append(sorted(P_.items()))
        s.letters = []
        for pp in s.parts:
            L = {0}
            for _, sz in pp: L = {x + e * sz for x in L for e in (1, -1)}
            s.letters.append(sorted(L))
        s.T1 = np.zeros(s.Gp.n, np.int64); np.add.at(s.T1, s.bidx, s.T)
        s.Sp = []

    def is_invariant(s, X):
        return all((np.asarray(X)[..., P] == np.asarray(X)).all() for P in s.perms)

    def compress(s, X):
        X = np.asarray(X); Y = np.zeros(X.shape[:-1] + (s.Gp.n,), np.int64)
        for b_ in range(s.Gp.n): Y[..., b_] = X[..., s.bidx == b_].sum(-1)
        return Y


def qaut_perm(G, axes, kind):
    """automorphism of the Q-part (axes) of G, identity elsewhere"""
    co = G.co.copy()
    a = co[:, axes]
    if kind == 'z2sq3':            # Z_2^2: (a, b) -> (b, a + b), order 3
        na = np.stack([a[:, 1], (a[:, 0] + a[:, 1]) % 2], 1)
    elif kind == 'singer7':        # Z_2^3 = GF(8), multiplication by t (t^3 = t + 1): (a, b, c) -> (c, a + c, b)
        na = np.stack([a[:, 2], (a[:, 0] + a[:, 2]) % 2, a[:, 1]], 1)
    elif kind == 'gl3_3':          # an order-3 element of GL(3, 2): permute the three coordinates cyclically
        na = np.stack([a[:, 2], a[:, 0], a[:, 1]], 1)
    else: raise ValueError(kind)
    co[:, axes] = na
    return G.idx(co)


def axis_mult_perm(G, axis, u):
    co = G.co.copy(); co[:, axis] = (co[:, axis] * u) % G.mods[axis]
    return G.idx(co)


def build(v, c, H1, q, s, qkind=None, Hmult=(), b=None):
    b = c - 1 if b is None else b
    Q = {4: (2, 2), 8: (2, 2, 2), 6: (2, 3)}[c]; nQ = len(Q)
    mods = tuple(Q) + tuple(H1) + (q,)
    G = AG(mods); qaxis = len(mods) - 1
    gens = [axis_mult_perm(G, qaxis, mgen(q, s))]
    if qkind: gens.append(qaut_perm(G, list(range(nQ)), qkind))
    for (ax, u) in Hmult: gens.append(axis_mult_perm(G, nQ + ax, u))
    Hmask = (G.co[:, :nQ] == 0).all(1)
    return PermSlice(mods, v, b, gens, qaxis, Hmask)


def scan(vs, cs, N=4000, out=None):
    import ab_gauss as AGs
    fo = open(out, 'a') if out else None
    for v in vs:
        for c in cs:
            if (v + 1) % c: continue
            h = (v + 1) // c - 1
            qk = {4: 'z2sq3', 8: 'singer7'}[c]
            for q, e in factorint(h).items():
                if e != 1 or q < 5: continue
                hp = h // q
                for Ht in abelian_types(hp):
                    Hopts = [()]
                    for ai, n in enumerate(Ht):
                        for (o, u) in unit_subgroup_gens(n): Hopts.append(((ai, u),))
                    for s in sorted(d for d in range(2, q) if (q - 1) % d == 0):
                        f = (q - 1) // s
                        for Hm in Hopts:
                            t0 = time.time()
                            try:
                                sl = build(v, c, Ht, q, s, qk, Hm)
                            except AssertionError as ex:
                                continue
                            rec = dict(v=v, c=c, H1=list(Ht), q=q, s=s, f=f, qaut=qk, Hmult=[list(x) for x in Hm],
                                       orbits=int(sl.r), L1=len(sl.breps))
                            w = sl.bsz.astype(np.int64)
                            emin = int(sum(int(w[j]) * min(y * y for y in L) for j, L in enumerate(sl.letters)))
                            rec['energy_ok'] = bool(4 * emin <= int(sl.T1[0]))
                            if rec['energy_ok'] and sl.r <= 400:
                                try:
                                    wh = AGs.whole(sl, N=N); rec['whole_log2E'] = None if wh.get('log2E') is None else float(wh['log2E'])
                                    rec['whole_rank'] = wh.get('rank')
                                except Exception as ex: rec['error'] = repr(ex)[:100]
                            rec['secs'] = round(time.time() - t0, 1)
                            print(json.dumps(rec), flush=True)
                            if fo: fo.write(json.dumps(rec) + "\n"); fo.flush()


