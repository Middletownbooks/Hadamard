r"""Common library for the Alpoege-style builders (b = 0 and b >= 3) with the staged method.

Group: G = Z_{n_1} x ... x Z_{n_r} (mixed radix, last axis fastest), elements are ravel indices.
Core condition (all b):  sum_k PAF_k(g) = T(g) with
    b = 0  (m = v):        T = 4v at 0, 0 elsewhere;
    b = 1  (m = v - 1):    T = 4m at 0, -4 elsewhere;
    b >= 3 (m = v - b = c h, H <= G of index c = b + 1):  T = 4m at 0, -4b on H \ {0}, +4 off H.
In characters: sum_k |X_k^(chi)|^2 = 4v, except 4b when chi != 1 is trivial on H (b >= 3); for b = 1, 4v - 4m.. at chi = 1.

Slice: a group S of automorphisms of G generated by per-axis scalars ((u_1, ..., u_r): x_i -> u_i x_i), preserving H;
x_k constant on the S-orbits.  Staging axis: one axis Z_q (q prime, Z_q <= H for b >= 3).  G' = the other axes.
  stage 1 (compression along Z_q):  y_k(b) = sum_z x_k(b, z),  sum_k PAF_{G'}(y_k)(b) = T1(b) = sum_z T(b, z);
     the value y_k(b) ranges over the signed sums of the sizes of the S_b-orbits partitioning the fibre {b} x Z_q
     (S_b = stabiliser of b), independently per S-orbit of G'.
  stage 2: for every nontrivial character psi of Z_q and every phi of G':  sum_k |X_k^(phi, psi)|^2 = 4v.
These are the exact conditions; theory/ab_verify_published.py checks them on the published 479, 347, 359 cores and on
the b = 0 core of H(892)."""
import math, itertools, json
import numpy as np


def factorint(n):
    f, p = {}, 2
    while p * p <= n:
        while n % p == 0:
            f[p] = f.get(p, 0) + 1; n //= p
        p += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f


def is_prime(n):
    return n >= 2 and all(n % p for p in range(2, int(n ** 0.5) + 1))


def primitive_root(p):
    fs = list(factorint(p - 1))
    for g in range(2, p):
        if all(pow(g, (p - 1) // r, p) != 1 for r in fs): return g
    return 1


class AG:
    """finite abelian group Z_{n1} x ... x Z_{nr} (last axis fastest)"""
    def __init__(s, mods):
        s.mods = tuple(int(x) for x in mods); s.n = int(np.prod(s.mods)) if s.mods else 1
        s.M = np.array(s.mods, np.int64)
        s.co = np.array(np.unravel_index(np.arange(s.n), s.mods)).T.reshape(s.n, len(s.mods)) if s.mods else np.zeros((1, 0), np.int64)

    def idx(s, c):
        c = np.asarray(c, np.int64) % s.M
        if len(s.mods) == 0: return np.zeros(c.shape[:-1], np.int64)
        return np.ravel_multi_index(tuple(np.moveaxis(c, -1, 0)), s.mods)

    def add(s, a, b):
        return s.idx(s.co[a] + s.co[b])

    def neg(s, a):
        return s.idx(-s.co[a])

    def act(s, u, a=None):
        """image of elements a (default all) under the per-axis scalar u"""
        a = np.arange(s.n) if a is None else a
        return s.idx(s.co[a] * np.array(u, np.int64))

    def shift_index(s, h):
        """permutation P with P[g] = g + h"""
        return s.idx(s.co + s.co[h])

    def order(s, a):
        o = 1; x = a
        while x != 0: x = s.add(x, a); o += 1
        return o

    def paf(s, X):
        """PAF over G of the rows of X (shape (..., n)); exact for integer X"""
        X = np.asarray(X)
        sh = X.shape[:-1]
        Y = X.reshape(sh + s.mods).astype(np.float64)
        ax = tuple(range(len(sh), len(sh) + len(s.mods)))
        F = np.fft.fftn(Y, axes=ax)
        R = np.fft.ifftn(np.abs(F) ** 2, axes=ax).real
        return np.rint(R).reshape(sh + (s.n,)).astype(np.int64)

    def psd(s, X):
        X = np.asarray(X); sh = X.shape[:-1]
        Y = X.reshape(sh + s.mods).astype(np.float64)
        ax = tuple(range(len(sh), len(sh) + len(s.mods)))
        return (np.abs(np.fft.fftn(Y, axes=ax)) ** 2).reshape(sh + (s.n,))


def target(G, v, b, Hmask=None):
    """the core target T on G (see module doc)"""
    T = np.zeros(G.n, np.int64)
    if b == 0:
        assert G.n == v; T[0] = 4 * v
    elif b == 1:
        assert G.n == v - 1; T[:] = -4; T[0] = 4 * G.n
    else:
        assert G.n == v - b and Hmask is not None
        T[:] = 4; T[Hmask] = -4 * b; T[0] = 4 * G.n
    return T


def subgroup_mask(G, gens):
    """mask of the subgroup generated by the elements gens"""
    S = {0}; frontier = [0]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = int(G.add(x, g))
            if y not in S: S.add(y); frontier.append(y)
    m = np.zeros(G.n, bool); m[list(S)] = True
    return m


def closure(G, gens):
    """all per-axis scalar tuples in the group generated by gens (as tuples reduced mod each axis)"""
    ident = tuple(1 % n if n > 1 else 0 for n in G.mods)
    red = lambda u: tuple(int(a) % n if n > 1 else 0 for a, n in zip(u, G.mods))
    S = {red(ident)}; frontier = [red(ident)]
    gens = [red(g) for g in gens]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = tuple((a * b) % n if n > 1 else 0 for a, b, n in zip(x, g, G.mods))
            if y not in S: S.add(y); frontier.append(y)
    return sorted(S)


class Slice:
    """S-invariant slice on G with a staging axis (the Z_q coordinate)"""
    def __init__(s, mods, v, b, gens, qaxis, Hmask=None):
        s.G = AG(mods); s.v, s.b = v, b
        s.S = closure(s.G, gens)
        s.Hmask = Hmask
        s.T = target(s.G, v, b, Hmask)
        G = s.G
        perms = [G.act(u) for u in s.S]
        if Hmask is not None:
            for P in perms: assert (Hmask[P] == Hmask).all(), "S does not preserve H"
        orb = -np.ones(G.n, np.int64); reps = []; sizes = []
        for g in range(G.n):
            if orb[g] >= 0: continue
            img = {int(P[g]) for P in perms}
            for x in img: orb[x] = len(reps)
            reps.append(g); sizes.append(len(img))
        s.orb, s.reps, s.sizes = orb, reps, np.array(sizes)
        s.r = len(reps)
        s.perms = perms
        # staging
        s.qaxis = qaxis; s.q = G.mods[qaxis]
        s.Gp = AG(tuple(n for i, n in enumerate(G.mods) if i != qaxis))
        # map g -> (b, z)
        s.bco = np.delete(G.co, qaxis, axis=1); s.zco = G.co[:, qaxis]
        s.bidx = s.Gp.idx(s.bco) if len(s.Gp.mods) else np.zeros(G.n, np.int64)
        # S acting on G'
        Sp = sorted({tuple(int(a) for i, a in enumerate(u) if i != qaxis) for u in s.S})
        s.Sp = Sp
        permsp = [s.Gp.act(u) for u in Sp] if len(s.Gp.mods) else [np.zeros(1, np.int64)]
        borb = -np.ones(s.Gp.n, np.int64); breps = []
        for bb in range(s.Gp.n):
            if borb[bb] >= 0: continue
            img = {int(P[bb]) for P in permsp}
            for x in img: borb[x] = len(breps)
            breps.append(bb)
        s.borb, s.breps = borb, breps
        s.bsz = np.bincount(borb)
        # fibre parts per G'-orbit representative: S-orbits meeting fibre(b) and their sizes inside it
        s.parts = []
        for bb in breps:
            P = {}
            for g in np.nonzero(s.bidx == bb)[0]:
                P[int(orb[g])] = P.get(int(orb[g]), 0) + 1
            s.parts.append(sorted(P.items()))
        s.letters = []
        for pp in s.parts:
            L = {0}
            for _, sz in pp: L = {x + e * sz for x in L for e in (1, -1)}
            s.letters.append(sorted(L))
        # stage-1 target on G'
        s.T1 = np.zeros(s.Gp.n, np.int64)
        np.add.at(s.T1, s.bidx, s.T)
        if Hmask is not None:
            s.Hpmask = np.zeros(s.Gp.n, bool); s.Hpmask[s.bidx[Hmask]] = True
        else:
            s.Hpmask = None

    def x_from_labels(s, lab):
        """lab: (..., r) signs per orbit -> x on G"""
        return np.asarray(lab)[..., s.orb]

    def compress(s, X):
        """y_k on G' from x_k on G"""
        X = np.asarray(X)
        Y = np.zeros(X.shape[:-1] + (s.Gp.n,), np.int64)
        for k in np.ndindex(X.shape[:-1]):
            np.add.at(Y[k], s.bidx, X[k])
        return Y

    def is_invariant(s, X):
        return all((np.asarray(X)[..., P] == np.asarray(X)).all() for P in s.perms)

    def describe(s):
        return dict(mods=s.G.mods, v=s.v, b=s.b, S_order=len(s.S), orbits=int(s.r), q=s.q, Gp=s.Gp.mods,
                    Gp_orbits=len(s.breps), letter_sets=sorted({tuple(L) for L in s.letters}, key=len)[:4],
                    T1_values=sorted(set(s.T1.tolist())))


def stage2_check(sl, X):
    """for every nontrivial character psi of Z_q and every phi of G': sum_k |X_k^(phi, psi)|^2 = 4v (numerically)"""
    G = sl.G
    F = np.fft.fftn(np.asarray(X, float).reshape((4,) + G.mods), axes=tuple(range(1, 1 + len(G.mods))))
    P = (np.abs(F) ** 2).sum(0)
    P = np.moveaxis(P, sl.qaxis, -1)
    return float(np.abs(P[..., 1:] - 4 * sl.v).max())


def alpha_congruence_mod(letters):
    """largest f0 >= 1 with every letter = +-1 (mod 2 f0) (odd letters), or the even analogue; returns f0"""
    allL = sorted({x for L in letters for x in L})
    f0 = 1
    for f in range(2, max(abs(x) for x in allL) + 2):
        if all((x - 1) % (2 * f) == 0 or (x + 1) % (2 * f) == 0 for x in allL): f0 = f
    return f0
