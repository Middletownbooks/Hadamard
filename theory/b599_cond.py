r"""Conditional stage-1 estimator for any b >= 3 GP slice whose multipliers act trivially on Q [E, counts exact].

Generalises theory/b599_flevels.py (calibrated: report/b599_answer.md section 3) to any configuration of
theory/ab_sweep.py with U acting on H' only (so every G'-orbit lies in one Q-coset):
  1. all Q-level solutions z (sum_k PAF_Q(z_k) = T_Q) up to translation, negation and Aut(Q) per block and block
     order: z_k = zmin_k 1 + 2 u_k (all coset sums have one parity), sum_k |u_k^(psi)|^2 = b for psi != 1;
  2. per z-quadruple: the y-quadruples with these compressions and stage-1 energy, counted exactly (DP over cosets),
     sampled uniformly, and the lattice Gaussian (theory/q523_gauss.gauss_bits) of the remaining lag classes:
     log2E(stage 1 | z) = H1 - C.
usage: python3 theory/b599_cond.py 'CFGJSON' [--N 3000] [--out FILE] [--maxquads 400]"""
