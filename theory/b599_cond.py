@njit(cache=True)
def _sig(V, SH):
    n = V.shape[0]; nl = SH.shape[0]; ng = SH.shape[1]
    out = np.zeros((n, nl), np.int64)
    for i in range(n):
        for L in range(nl):
            acc = 0
            for g in range(ng): acc += V[i, g] * V[i, SH[L, g]]
            out[i, L] = acc
    return out


class Cond:
    def __init__(self, cfg, sl=None, Qmods=None, qc=None):
        """split G (default): Q = the first nQ axes of G'.  Non-split: pass the Slice sl, the quotient Qmods and the
        coset index qc of every element of G' (a homomorphism G' -> Q with kernel H')"""
        self.cfg = cfg; sl = W.build(cfg) if sl is None else sl; self.sl = sl
        Gp = sl.Gp; nQ = cfg['nQ']; self.b = cfg['b']; self.v = cfg['v']
        if qc is None:
            self.Q = AG(Gp.mods[:nQ]); self.qc = self.Q.idx(Gp.co[:, :nQ])
        else:
            self.Q = AG(tuple(Qmods)); self.qc = np.asarray(qc, np.int64)
        self.c = self.Q.n
        L1 = len(sl.breps); self.L1 = L1
        self.oq = np.zeros(L1, np.int64)
        for j in range(L1):
            qs = set(self.qc[sl.borb == j].tolist())
            assert len(qs) == 1, "an orbit spans several Q-cosets (U acts on Q): not supported"
            self.oq[j] = qs.pop()
        self.w = sl.bsz.astype(np.int64)
        self.lets = [np.array(sorted(L), np.int64) for L in sl.letters]
        self.cos = [np.nonzero(self.oq == q)[0] for q in range(self.c)]
        Up = sl.permsp if getattr(sl, 'permsp', None) is not None else [Gp.act(u) for u in sl.Sp]
        self.reps, _ = lag_reps(Gp, Up)
        self.reps = np.array(self.reps, np.int64)
        self.SH = np.array([Gp.idx(Gp.co + Gp.co[r]) for r in self.reps], np.int64)
        self.T1sig = sl.T1[self.reps].astype(np.int64)
        self.T0 = int(sl.T1[0])
        self.par = int(sum(self.w[self.cos[0]]) % 2)

    def sig(self, V):
        V = np.atleast_2d(np.asarray(V, np.int64))
        return _sig(np.ascontiguousarray(V[:, self.sl.borb]), self.SH)

    # ------------------------------------------------------------- Q-level
    def qautos(self):
        """automorphisms of Q as index permutations (generated by the unit scalars per axis and, for Z_2^r, GL)"""
        Q = self.Q; mods = Q.mods; perms = set()
        if all(m == 2 for m in mods):
            r = len(mods)
            for M in itertools.product((0, 1), repeat=r * r):
                A = np.array(M).reshape(r, r)
                if round(abs(np.linalg.det(A))) % 2 == 0: continue
                img = (Q.co @ A.T) % 2
                perms.add(tuple(Q.idx(img).tolist()))
        else:
            unit_opts = [[u for u in range(1, m) if math.gcd(u, m) == 1] if m > 1 else [0] for m in mods]
            for us in itertools.product(*unit_opts):
                perms.add(tuple(Q.act(us).tolist()))
        return [np.array(p) for p in perms]

    def canon_tn(self, u):
        """canonical representative of u under translation by Q and negation (u -> max u - u)"""
        best = None
        for v in (np.asarray(u), max(u) - np.asarray(u)):
            for t in range(self.c):
                y = v[self.Q.shift_index(t)]; y = tuple((y - y.min()).tolist())
                if best is None or y < best: best = y
        return best

    def qlevel_quads(self, umax=3):
        """one representative per class of Q-level deviation quadruples (u_0..u_3), z_k = zmin_k + 2 u_k:
        sum_k |u_k^(psi)|^2 = b for every psi != 1; classes under per-block translation and negation, block order,
        and a global automorphism of Q"""
        c, b = self.c, self.b
        bound = b * (c - 1) / c + 1e-9
        autos = self.qautos()
        tn = {}
        for u in itertools.product(range(umax + 1), repeat=c):
            if min(u) != 0: continue
            ua = np.array(u, float)
            if ((ua - ua.mean()) ** 2).sum() > bound: continue
            tn.setdefault(self.canon_tn(u), None)
        reps = sorted(tn)
        prof = np.array([np.rint(np.abs(np.fft.fftn(np.array(r, float).reshape(self.Q.mods))).ravel()[1:] ** 2) for r in reps], np.int64)
        target = np.full(c - 1, b, np.int64)
        ok = (prof <= b).all(1); idx = np.nonzero(ok)[0]
        pairs = defaultdict(list)
        for ii, i in enumerate(idx):
            for j in idx[ii:]:
                pairs[tuple((prof[i] + prof[j]).tolist())].append((int(i), int(j)))
        found = {}
        for key, lst in pairs.items():
            need = tuple((target - np.array(key)).tolist())
            if need not in pairs: continue
            for (i, j) in lst:
                for (k, l) in pairs[need]:
                    if (k, l) < (i, j): continue
                    us = [reps[i], reps[j], reps[k], reps[l]]
                    ckey = min(tuple(sorted(self.canon_tn(tuple(np.array(u)[P].tolist())) for u in us)) for P in autos)
                    if ckey not in found: found[ckey] = us
        return found

    def rows_for(self, us):
        c = self.c; v = self.v; par = self.par
        U = [2 * sum(u) for u in us]
        lim = int(math.isqrt(4 * v) // c) + 3
        sols = []
        rng = [m for m in range(-lim, lim + 1) if m % 2 == par % 2]
        for zm in itertools.product(rng, repeat=4):
            if sum((c * zm[k] + U[k]) ** 2 for k in range(4)) == 4 * v: sols.append(zm)
        return sols

    # ------------------------------------------------------------- per-block sampler
    def block_sampler(self, z):
        return BlockSampler(self, z)

    def budget(self, Z, N=3000, seed=1):
        rng = np.random.default_rng(seed)
        samp = [BlockSampler(self, Z[k]) for k in range(4)]
        if any(not s.N for s in samp): return dict(H1=None, note="a block has no vector")
        Ns = [s.N for s in samp]; T0 = self.T0
        P01 = defaultdict(list)
        for e0, c0 in Ns[0].items():
            for e1, c1 in Ns[1].items():
                if e0 + e1 <= T0: P01[e0 + e1].append((e0, e1, c0 * c1))
        splits = []; wts = []
        for e2, c2 in Ns[2].items():
            for e3, c3 in Ns[3].items():
                for (e0, e1, c01) in P01.get(T0 - e2 - e3, []):
                    splits.append((e0, e1, e2, e3)); wts.append(c01 * c2 * c3)
        tot = sum(wts)
        if not tot: return dict(H1=None, note="energy infeasible")
        H1 = math.log2(tot)
        p = np.array([x / tot for x in wts], float)
        pick = rng.choice(len(splits), size=N, p=p)
        Y = np.zeros((N, 4, self.L1), np.int64)
        for i, si in enumerate(pick):
            for k in range(4): Y[i, k] = samp[k].draw(splits[si][k], rng)
        V = self.sig(Y.reshape(4 * N, self.L1)).reshape(N, 4, -1).sum(1)
        gb = gauss_bits(V, self.T1sig)
        out = dict(H1=round(H1, 2), bits=gb.get('bits'), rank=gb.get('rank'), in_lattice=gb.get('in_lattice'),
                   mahal=gb.get('mahal'))
        out['log2E'] = round(H1 - gb['bits'], 2) if gb.get('in_lattice') and gb.get('bits') is not None and np.isfinite(gb['bits']) else -math.inf
        return out


class BlockSampler:
    """uniform block vectors with Q-compression z and energy E: per coset a forward DP over its orbits on
    (partial sum, partial energy), sampled backwards; cosets combined by an energy DP"""
    def __init__(self, C, z, Emax=None):
        self.C = C; z = np.asarray(z, np.int64); Emax = C.T0 if Emax is None else Emax
        self.cos = []
        for q in range(C.c):
            orbs = list(C.cos[q])
            tabs = [{(0, 0): 1}]
            for o in orbs:
                w = int(C.w[o]); nd = defaultdict(int)
                for (sm, e), m in tabs[-1].items():
                    for y in C.lets[o].tolist():
                        e2 = e + w * y * y
                        if e2 <= Emax: nd[(sm + w * y, e2)] += m
                tabs.append(dict(nd))
            byE = defaultdict(int)
            for (sm, e), m in tabs[-1].items():
                if sm == int(z[q]): byE[e] += m
            self.cos.append((orbs, tabs, dict(byE)))
        self.cnt = [None] * (C.c + 1); self.cnt[C.c] = {0: 1}
        for q in range(C.c - 1, -1, -1):
            nd = defaultdict(int)
            for E, cc in self.cnt[q + 1].items():
                for e, m in self.cos[q][2].items():
                    if E + e <= Emax: nd[E + e] += cc * m
            self.cnt[q] = dict(nd)
        self.N = self.cnt[0]
        self.z = z

    def draw(self, E, rng):
        C = self.C; out = np.zeros(C.L1, np.int64); R = E
        for q in range(C.c):
            orbs, tabs, byE = self.cos[q]
            es = [e for e in byE if (R - e) in self.cnt[q + 1]]
            w = np.array([byE[e] * self.cnt[q + 1][R - e] for e in es], float)
            e = es[rng.choice(len(es), p=w / w.sum())]
            sm = int(self.z[q]); ee = e
            for i in range(len(orbs) - 1, -1, -1):
                o = orbs[i]; wo = int(C.w[o]); ys = C.lets[o].tolist()
                ws = np.array([tabs[i].get((sm - wo * y, ee - wo * y * y), 0) for y in ys], float)
                y = ys[rng.choice(len(ys), p=ws / ws.sum())]
                out[o] = y; sm -= wo * y; ee -= wo * y * y
            assert sm == 0 and ee == 0
            R -= e
        return out


