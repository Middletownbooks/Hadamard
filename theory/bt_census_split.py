r"""Census of split k = 4 structures (different symmetry groups per block, the 1916 shape) [P screens, M Q-level gate,
E Q-level stratified count read at the true target].

For a common-S census record (theory/bt_census_run.py) and each proper subgroup S' of S of index 2 or 3 generated by
powers of the generators, the split structure has blocks 1, 4 invariant under S and blocks 2, 3 under S' (1916: S of
order 12 with 46 orbits, S' of order 4 with 128 orbits).  The blocks are no longer interchangeable, so the Q-level
runs over every ordered signed row vector (all permutations and signs of the sorted patterns), each with weight 1.
Screens: coset-Parseval (subgroups invariant under every block's group), Theorem alpha with the element required in
every block's group (S' suffices since S' <= S), Lemma R likewise.
usage: python3 theory/bt_census_split.py OUT.jsonl CENSUS.jsonl[,...] [--ns 839,863] [--rmin 16] [--rmax 70]
       [--part i/W]
"""
import sys, os, json, math, time, argparse, itertools, hashlib
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bt_engine as E, bt_chain as C, bt_gates as BG, bt_census_run as R, bt_census2 as C2, bt_thm_rigid as TR


def split_structures(rec):
    """split variants of a common-S k = 4 record: list of (label, per-block generator lists)"""
    gens = [np.array(M) for M in rec['gens']]
    st = R.build(rec)
    G = st.G
    P = [G.perm_of(M) for M in gens]
    full = E.group_elements(P, G.n, cap=20000)
    order = len(full)
    cands = []
    pw = lambda M, k: np.linalg.matrix_power(M, k)
    choices = []
    for ks in itertools.product(*[[1, 2, 3] for _ in gens]):
        choices.append([pw(M, k) for M, k in zip(gens, ks)])
    for g in gens:
        choices.append([g])
    seen = set(); out = []
    for sub in choices:
        el = E.group_elements([G.perm_of(M) for M in sub], G.n, cap=20000)
        idx = order // max(1, len(el))
        if len(el) == order or idx not in (2, 3) or order % len(el):
            continue
        key = tuple(sorted(tuple(p) for p in el))
        h = hash(key)
        if h in seen:
            continue
        seen.add(h)
        out.append((f'index {idx}', [M.tolist() for M in sub]))
    return out


def ordered_patterns(st):
    pats = set()
    for p in BG.row_patterns(st):
        for q in itertools.permutations(p):
            pats.add(q)
    return sorted(pats)


def alpha_all_blocks(st):
    """Theorem alpha for split structures: sigma (fixing K pointwise, order 3 on Q = Z_2^2) in every block's group"""
    if st.q != 4 or len(st.Kel) < 2:
        return False
    common = None
    for i in range(4):
        els = E.group_elements(st.bperms[i], st.G.n, cap=5000)
        good = set()
        for p in els:
            if not (p[st.Kel] == st.Kel).all():
                continue
            act = np.array([st.coset[p[st.coset_rep[c]]] for c in range(st.q)])
            if not (act == np.arange(st.q)).all() and (act[act[act]] == np.arange(st.q)).all():
                good.add(p.tobytes())
        common = good if common is None else common & good
    return bool(common)


def evaluate(base, label, bgens, N=1200, maxq=2, seed=1):
    t0 = time.time()
    mods = tuple(base['Pmods']) + tuple(base['Omods'])
    st0 = R.build(base)
    Kgens = []
    G = st0.G
    PG = E.Grp(tuple(base['Pmods']))
    for g in base['K2']:
        if g:
            Kgens.append(tuple(PG.co[g]) + (0,) * len(base['Omods']))
    for j in range(len(base['Omods'])):
        v = [0] * len(mods); v[len(base['Pmods']) + j] = 1; Kgens.append(tuple(v))
    blocks = [[np.array(M) for M in bgens[i]] for i in range(4)]
    st = E.BStruct(mods, Kgens, 'k', blocks, name=f"{base['n']} split")
    out = dict(n=base['n'], fam='k4split', base_key=base['key'], Pmods=base['Pmods'], Omods=base['Omods'],
               K2=base['K2'], label=label, bgens=[[np.asarray(M).tolist() for M in b] for b in blocks],
               order=base['order'], r=list(map(int, st.r)), e=int(st.e))
    out['key'] = hashlib.sha1(json.dumps([out['n'], out['Pmods'], out['Omods'], out['K2'], out['bgens']]).encode()).hexdigest()[:16]
    rule = sum(st.r) - 6.5 * st.e
    out['rule'] = rule
    cp = st.coset_parseval()
    if any(d['dead'] for d in cp):
        out['verdict'] = 'no core [P] (coset-Parseval)'; out['secs'] = round(time.time() - t0, 1); return out
    if alpha_all_blocks(st):
        out['verdict'] = 'no core [P] (Theorem alpha)'; out['secs'] = round(time.time() - t0, 1); return out
    if TR.rigid(st) is not None:
        out['verdict'] = 'no core [P] (Lemma R)'; out['secs'] = round(time.time() - t0, 1); return out
    if rule < -45:
        out['verdict'] = f'skipped (sum r - 6.5e = {rule:.1f} < -45)'; out['secs'] = round(time.time() - t0, 1); return out
    g = BG.Gates(st)
    try:
        qs = g.q_level(patterns=ordered_patterns(st))
    except MemoryError as ex:
        out['verdict'] = f'Q-level cap ({ex})'; out['secs'] = round(time.time() - t0, 1); return out
    out['q_solutions'] = int(sum(len(q[1]) for q in qs))
    if not qs:
        out['verdict'] = 'no core [M] (Q-level empty)'; out['secs'] = round(time.time() - t0, 1); return out
    rng = np.random.default_rng(seed)
    tot = 0.0
    for rows, sol, L in qs:
        idx = np.arange(len(sol)) if len(sol) <= maxq else rng.choice(len(sol), maxq, replace=False)
        vals = []
        for k in idx:
            s = sol[k]
            zs = [L[i][0][s[i]] for i in range(4)]
            lm = sum(math.log2(L[i][1][s[i]]) for i in range(4))
            r = BG.stratified_bits(st, g.qQ, zs, N=N, seed=seed + int(k))
            vals.append(lm - r['bits'] if np.isfinite(r['bits']) else -math.inf)
        vals = np.array(vals)
        tot += len(sol) * np.mean(np.where(np.isfinite(vals), 2.0 ** vals, 0.0))
    out['log2E_Q'] = round(math.log2(tot), 2) if tot > 0 else None
    out['verdict'] = 'passes Q-level'
    out['secs'] = round(time.time() - t0, 1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out'); ap.add_argument('census')
    ap.add_argument('--ns', default=None); ap.add_argument('--rmin', type=int, default=16)
    ap.add_argument('--rmax', type=int, default=70); ap.add_argument('--part', default='0/1')
    a = ap.parse_args()
    pi, pw = map(int, a.part.split('/'))
    ns = set(map(int, a.ns.split(','))) if a.ns else None
    done = set()
    if os.path.exists(a.out):
        for x in open(a.out):
            done.add(json.loads(x)['base_key'] + '|' + json.loads(x)['label'] + json.dumps(json.loads(x)['bgens'][1]))
    base = []
    for f in a.census.split(','):
        for x in open(f):
            d = json.loads(x)
            if 'fam' in d and d['fam'] != 'k4':
                continue
            if ns and d['n'] not in ns:
                continue
            if not (a.rmin <= d['r'] <= a.rmax) or 'coset-Parseval' in d.get('verdict', '') \
                    or 'alpha' in d.get('verdict', ''):
                continue
            base.append(d)
    base.sort(key=lambda d: (d['n'], d['r']))
    k = 0
    for d in base:
        for label, sub in split_structures(d):
            k += 1
            if (k - 1) % pw != pi:
                continue
            bg = [d['gens'], sub, sub, d['gens']]
            tag = d['key'] + '|' + label + json.dumps([np.asarray(M).tolist() for M in sub])
            if tag in done:
                continue
            try:
                res = evaluate(d, label, bg)
            except Exception as ex:
                res = dict(n=d['n'], fam='k4split', base_key=d['key'], label=label, bgens=[d['gens'], sub, sub, d['gens']],
                           key='err' + d['key'], verdict=f'error: {type(ex).__name__}: {ex}')
            done.add(tag)
            with open(a.out, 'a') as fo:
                fo.write(json.dumps(res) + '\n')
            print(json.dumps({x: res.get(x) for x in ('n', 'order', 'label', 'r', 'e', 'verdict', 'q_solutions',
                                                      'log2E_Q', 'secs')}), flush=True)


if __name__ == '__main__':
    main()
