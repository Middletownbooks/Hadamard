"""Enumerate skew multiplier slices (G, H) for a given odd v (prompt §4 step 2).

- Cyclic G = Z_v: every subgroup of Z_v^* of odd order generated by at most two elements (odd order => -1 not in H).
- Non-cyclic G = Z_p x Z_p x Z_m (p^2 | v, p odd, p not dividing m): H = <(M, u)>, <(M,1),(1,u)> with M in odd-order
  conjugacy-class representatives of GL(2, p) (scalars, split torus diag(a, b), Singer elements, unipotent) and u an
  odd-order unit of Z_m. Subgroups are deduplicated by their orbit signature (sorted orbit and class sizes), which may
  merge non-conjugate subgroups with equal signatures; the screen records the generators actually used.
Kept: rmin <= orbits <= rmax.
"""
import math
from functools import reduce
import numpy as np
from sympy import factorint, primitive_root, isprime
from skew_lib import Group, Struct, aut_diag, aut_block

def units(n):
    return [u for u in range(1, n) if math.gcd(u, n) == 1] if n > 1 else [0]

def mult_order(u, n):
    if n == 1: return 1
    k, x = 1, u % n
    while x != 1: x = x * u % n; k += 1
    return k

def subgroup(gens, n):
    S = {1 % n}; fr = [1 % n]
    while fr:
        x = fr.pop()
        for g in gens:
            y = x * g % n
            if y not in S: S.add(y); fr.append(y)
    return frozenset(S)

def odd_subgroups_cyclic(n, maxorder=None, minorder=1):
    odd = [u for u in units(n) if mult_order(u, n) % 2 == 1]
    cyc = {}
    for u in odd:
        S = subgroup([u], n)
        if S not in cyc: cyc[S] = (u,)
    allg = dict(cyc)
    cl = list(cyc.items())
    for i in range(len(cl)):
        for j in range(i + 1, len(cl)):
            S = subgroup([cl[i][1][0], cl[j][1][0]], n)
            if S not in allg: allg[S] = (cl[i][1][0], cl[j][1][0])
    out = [(len(S), g) for S, g in allg.items() if len(S) >= minorder and (maxorder is None or len(S) <= maxorder)]
    return sorted(out)

def cyclic_slices(v, rmin=24, rmax=130):
    G = Group([v])
    res = []
    lo = max(1, (v - 1) // (rmax - 1)); hi = (v - 1) / (rmin - 1) + 1
    for h, gens in odd_subgroups_cyclic(v):
        if h > hi * 3 or h < lo / 3: continue
        st = Struct(G, [G.perm(aut_diag([v], [g])) for g in gens], label=f'Z{v}<{",".join(map(str, gens))}>')
        if rmin <= st.r <= rmax:
            st.H = h; st.gdesc = dict(group=[v], gens=[[g] for g in gens])
            res.append(st)
    return res

def gl2_odd_reps(p):
    """Odd-order elements of GL(2,p) up to conjugacy, as 2x2 integer matrices, with their orders."""
    reps = []
    g = primitive_root(p)
    oddpart = lambda n: n // (2 ** (n & -n).bit_length() // 2) if n else n
    # split torus diag(g^i, g^j), up to swap, odd order: i, j multiples of the 2-part of p-1
    t = (p - 1) & -(p - 1)
    for i in range(0, p - 1, t):
        for j in range(i, p - 1, t):
            M = [[pow(g, i, p), 0], [0, pow(g, j, p)]]
            reps.append(('torus', M))
    # unipotent times scalar of odd order
    for i in range(0, p - 1, t):
        a = pow(g, i, p); reps.append(('unip', [[a, a], [0, a]]))
    # Singer: elements of F_{p^2}^* of odd order not in F_p: companion matrix of x^2 - tr x + nm
    q2 = p * p - 1; t2 = q2 & -q2
    # find a primitive element of F_{p^2} = F_p[x]/(x^2 - c x - d)
    for c in range(p):
        for d in range(1, p):
            # test irreducibility and primitivity
            def mul(a, b):  # (a0 + a1 x)(b0 + b1 x), x^2 = c x + d
                a0, a1 = a; b0, b1 = b
                return ((a0 * b0 + a1 * b1 * d) % p, (a0 * b1 + a1 * b0 + a1 * b1 * c) % p)
            def pw(a, e):
                r = (1, 0)
                while e:
                    if e & 1: r = mul(r, a)
                    a = mul(a, a); e >>= 1
                return r
            if any((x * x - c * x - d) % p == 0 for x in range(p)): continue
            fac = factorint(q2)
            if all(pw((0, 1), q2 // f) != (1, 0) for f in fac):
                prim = (c, d, mul, pw); break
        else: continue
        break
    c, d, mul, pw = prim
    seen = set()
    for k in range(t2, q2, t2):  # odd-order powers w^k
        a = pw((0, 1), k)
        if a[1] == 0: continue  # in F_p: scalar, already among torus reps
        # matrix of multiplication by a0 + a1 x on basis (1, x)
        a0, a1 = a
        M = [[a0, a1 * d % p], [a1, (a0 + a1 * c) % p]]
        key = (tuple(sorted([k % q2, k * p % q2])))
        if key in seen: continue
        seen.add(key); reps.append(('singer', M))
    return reps

def noncyclic_slices(v, rmin=24, rmax=130):
    res = []
    for p, e in factorint(v).items():
        if e != 2: continue
        m = v // (p * p)
        mods = [p, p, m] if m > 1 else [p, p]
        G = Group(mods)
        reps = gl2_odd_reps(p)
        uodd = [u for u in units(m) if m > 1 and mult_order(u, m) % 2 == 1] if m > 1 else [1]
        ucyc = {}
        for u in uodd:
            S = subgroup([u], m) if m > 1 else frozenset([0])
            ucyc.setdefault(S, u)
        us = sorted(ucyc.values()) if m > 1 else [None]
        sigs = set()
        def add(gens, desc):
            st = Struct(G, gens, label=desc)
            if not (rmin <= st.r <= rmax) or not st.skew_ok: return
            sig = (tuple(sorted(st.osize)), tuple(sorted(st.csize)))
            if sig in sigs: return
            sigs.add(sig); st.gdesc = dict(group=mods, gens=desc); res.append(st)
        for kind, M in reps:
            for u in us:
                if m > 1:
                    f = aut_block(mods, [(0, 2, M), (2, 3, [[u]])])
                    add([G.perm(f)], [(kind, M, u)])
                    if u != 1:
                        f1 = aut_block(mods, [(0, 2, M)]); f2 = aut_block(mods, [(2, 3, [[u]])])
                        add([G.perm(f1), G.perm(f2)], [(kind, M, 1), ('id', None, u)])
                else:
                    add([G.perm(aut_block(mods, [(0, 2, M)]))], [(kind, M)])
    return res

def all_slices(v, rmin=24, rmax=130):
    return cyclic_slices(v, rmin, rmax) + noncyclic_slices(v, rmin, rmax)
